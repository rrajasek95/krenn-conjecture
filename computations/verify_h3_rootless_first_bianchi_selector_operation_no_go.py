    for h, kappa in product(range(-3, 4), repeat=2):
        constant = kappa * h
        u_coefficient = -kappa
        require(u_coefficient == 0 if kappa == 0 else u_coefficient != 0,
                "monic coefficient extraction failed")
        samples.append((h, kappa, constant, u_coefficient))
    # The proof is coefficientwise over A/I and therefore does not use the
    # sampled integers; the samples discriminate the sign and monicity.
    return {"sample_count": len(samples), "u_coefficient": "-kappa",
            "theorem": "kappa*(H-u) in I[u] iff kappa in I",
            "localization": "arbitrary u-free selector/curvature open"}


