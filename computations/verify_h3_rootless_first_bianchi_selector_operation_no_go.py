def source_labelled_bar_audit() -> dict[str, object]:
    """A target-zero normalized bar has no pure companion coefficient."""
    words = tuple(product(range(3), repeat=8))
    pure = tuple((colour,) * 8 for colour in range(3))
    index = {word: position for position, word in enumerate(words)}
    # Complete full-nine companion cancellation is the identity on word
    # labels.  Target projection is the three pure coordinate probes.
    probes = []
    for word in pure:
        row = [Q(0)] * len(words)
        row[index[word]] = Q(1)
        probes.append(row)
    require(rank(probes) == 3, "pure target probes lost independence")

    # Exercise every pure-vs-mixed reduced contrast.  It has normalized
    # augmentation zero, but its unique companion cancellation has the
    # corresponding nonzero labelled pure target.
    reference_mixed = next(word for word in words if len(set(word)) > 1)
    contrasts = []
    for colour, pure_word in enumerate(pure):
        vector = {pure_word: Q(1), reference_mixed: Q(-1)}
        augmentation = sum(vector.values(), Q(0))
        target = tuple(vector.get(word, Q(0)) for word in pure)
        require(augmentation == 0, "reduced bar is not reduced")
        require(target == tuple(Q(i == colour) for i in range(3)), target)
        contrasts.append({"pure": colour, "augmentation": 0,
                          "target": list(map(int, target))})

    # Linear theorem: target zero is coefficientwise zero on every pure
    # source word.  Test it on a basis for the 6558-dimensional mixed part.
    mixed = tuple(word for word in words if word not in pure)
    require(len(mixed) == 6558, "mixed word count changed")
    for word in mixed:
        require(all(word != pure_word for pure_word in pure),
                "mixed basis vector acquired a pure target")
    return {"word_labels": len(words), "mixed_target_zero_basis": len(mixed),
            "pure_target_rank": 3, "contrasts": contrasts}


