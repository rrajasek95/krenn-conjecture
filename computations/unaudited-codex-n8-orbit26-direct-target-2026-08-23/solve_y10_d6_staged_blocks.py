"""Target-rooted staged d6 Macaulay blocks for the y10*t^2 dead row.

The full d6 rowspace is generated by normalized originals times homogeneous
degree-two monomials; complete d5*d1 columns are exact redundant helpers.
We first close only the t-free y6 leading layer.  This is the last layer on
which literal off-support monomials retain their exact port grading.  Lower
y5/y4 tails are deliberately not used for graph closure until the y6 kernel
has been transferred.
"""

