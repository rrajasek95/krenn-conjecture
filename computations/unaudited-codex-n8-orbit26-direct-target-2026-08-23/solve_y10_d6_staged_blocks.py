def require(condition, detail):
    if not condition:
        raise RuntimeError(detail)


spec = importlib.util.spec_from_file_location("y10_d6_staged_first", FIRST_PATH)
FIRST = importlib.util.module_from_spec(spec)
require(spec.loader is not None, "cannot load first homogeneous checker")
spec.loader.exec_module(FIRST)


def quotient(dividend, divisor):
    answer = list(dividend)
    for value in divisor:
        require(value in answer, "requested non-divisor quotient")
        answer.remove(value)
    return bytes(answer)


def top_polynomial(polynomial, multiplier):
    answer = Counter()
    for row, coefficient in polynomial.items():
        if len(row) == 4:
            answer[FIRST.multiply(row, multiplier)] += coefficient
    return {row: value for row, value in answer.items() if value}


def singleton_column_peel(column_to_rows, row_to_columns):
    """Exact triangular independence certificate from private nonzero rows."""
    active_columns = set(column_to_rows)
    active_by_row = {
        row: set(columns) & active_columns
        for row, columns in row_to_columns.items()
    }
    queue = deque(sorted(row for row, columns in active_by_row.items()
                         if len(columns) == 1))
    pivot_ledger = []
    while queue:
        row = queue.popleft()
        owners = active_by_row[row]
        if len(owners) != 1:
            continue
        column = next(iter(owners))
        if column not in active_columns:
            continue
        active_columns.remove(column)
        pivot_ledger.append((column, row))
        for incident_row in sorted(column_to_rows[column]):
            incident_owners = active_by_row[incident_row]
            incident_owners.discard(column)
            if len(incident_owners) == 1:
                queue.append(incident_row)
    return pivot_ledger, active_columns


def close_top_layer(seeds, originals, top_term_to_codes, multiplier_length):
    """Inverse-incidence closure for original columns with fixed y multiplier."""
    output_degree = 4 + multiplier_length
    columns = set(seeds)
    pending = deque(sorted(seeds))
    rows = set()
    row_to_columns = defaultdict(set)
    while pending:
        code, multiplier = pending.popleft()
        require(len(multiplier) == multiplier_length,
                "fixed-layer multiplier length changed")
        polynomial = top_polynomial(originals[code], multiplier)
        for row in polynomial:
            require(len(row) == output_degree, "top output degree changed")
            if row not in rows:
                rows.add(row)
                for positions in combinations(range(output_degree), 4):
                    term = bytes(row[index] for index in positions)
                    owners = top_term_to_codes.get(term)
                    if not owners:
                        continue
                    complement = quotient(row, term)
                    require(len(complement) == multiplier_length,
                            "inverse-incidence complement changed")
                    for owner, _coefficient in owners:
                        candidate = (owner, complement)
                        row_to_columns[row].add(candidate)
                        if candidate not in columns:
                            columns.add(candidate)
                            pending.append(candidate)
            row_to_columns[row].add((code, multiplier))
    column_to_rows = {}
    for column in sorted(columns):
        polynomial = top_polynomial(originals[column[0]], column[1])
        column_to_rows[column] = set(polynomial)
        for row in polynomial:
            row_to_columns[row].add(column)
    return columns, rows, column_to_rows, row_to_columns


def exact_top_echelon(columns, originals):
    """Column echelon on one fixed encoded-y layer over Q."""
    pivots = {}
    dependent = []
    for column in sorted(columns):
        work = dict(top_polynomial(originals[column[0]], column[1]))
        while work:
            lead = min(work)
            coefficient = work[lead]
            reducer = pivots.get(lead)
            if reducer is None:
                work = {row: value / coefficient
                        for row, value in work.items()}
                pivots[lead] = work
                break
            for row, value in reducer.items():
                FIRST.add_value(work, row, -coefficient * value)
        if not work:
            dependent.append(column)
    return pivots, dependent


def main():
    incident = json.loads(D6_RESULTS.read_text())
    require(incident["logical_sha256"]
            == "447409df3f67c76ef437937b3e041065adc83d96d6e90a35b091f8638b80d1b5",
            "corrected homogeneous d6 census changed")
    require(not incident["original_leads_dividing_target"]
            and not incident["degree5_leads_dividing_target"],
            "a completed d4/d5 pivot divides the target")
    originals, _lead_to_code = FIRST.original_basis()

    top_term_to_codes = defaultdict(list)
    top_occurrences = 0
    for code, polynomial in originals.items():
        for row, coefficient in polynomial.items():
            if len(row) == 4:
                top_term_to_codes[row].append((code, coefficient))
                top_occurrences += 1
    require(top_occurrences == 567_338, "original top occurrence census changed")

    seeds = set()
    seed_target_rows = defaultdict(set)
    for record in incident["incident_records"]:
        if record["kind"] != "original_times_homogeneous_d2":
            continue
        multiplier = bytes.fromhex(record["multiplier_y"])
        if len(multiplier) != 2:
            continue
        key = (record["source_code"], multiplier)
        seeds.add(key)
        seed_target_rows[key].update(bytes.fromhex(row[0])
                                     for row in record["target_rows"])
    require(len(seeds) == 108, "y6-stage seed census changed")

    columns = set(seeds)
    pending_columns = deque(sorted(seeds))
    rows = set()
    row_to_columns = defaultdict(set)
    while pending_columns:
        code, multiplier = pending_columns.popleft()
        polynomial = top_polynomial(originals[code], multiplier)
        for row in polynomial:
            if row in rows:
                row_to_columns[row].add((code, multiplier))
                continue
            rows.add(row)
            # Exact inverse top incidence: every y6 column is one y4 source
            # term times its complementary encoded-y degree-two multiplier.
            for positions in combinations(range(6), 4):
                term = bytes(row[index] for index in positions)
                owners = top_term_to_codes.get(term)
                if not owners:
                    continue
                complement = quotient(row, term)
                require(len(complement) == 2, "top complement lost degree two")
                for owner, _coefficient in owners:
                    candidate = (owner, complement)
                    row_to_columns[row].add(candidate)
                    if candidate not in columns:
                        columns.add(candidate)
                        pending_columns.append(candidate)
            require(row_to_columns[row], "top row lost every provider")

    # Exact bipartite connected components on the closed top packet.
    column_to_rows = {}
    for column in sorted(columns):
        polynomial = top_polynomial(originals[column[0]], column[1])
        column_to_rows[column] = set(polynomial)
        for row in polynomial:
            row_to_columns[row].add(column)
    unseen = set(columns)
    components = []
    while unseen:
        first = min(unseen)
        component_columns = {first}
        component_rows = set()
        queue = deque([first])
        unseen.remove(first)
        while queue:
            column = queue.popleft()
            for row in column_to_rows[column]:
                if row in component_rows:
                    continue
                component_rows.add(row)
                for neighbour in row_to_columns[row]:
                    if neighbour in unseen:
                        unseen.remove(neighbour)
                        component_columns.add(neighbour)
                        queue.append(neighbour)
        seed_count = len(component_columns & seeds)
        components.append((component_columns, component_rows, seed_count))
    components.sort(key=lambda item: (-item[2], -len(item[0]), min(item[0])))

    pivot_ledger, residual_columns = singleton_column_peel(
        column_to_rows, row_to_columns
    )
    require(not residual_columns,
            "the target-rooted y6 packet retained a top-kernel core")

    # Once the y6 columns are certified independent, none can participate in
    # a vector whose leading row lies at y5 or y4.  Continue with precisely
    # the original*t columns that directly touch a remaining target divisor.
    y5_seeds = set()
    target_y5_rows = set()
    target_y4_rows = set()
    for item in incident["incident_records"]:
        if item["kind"] != "original_times_homogeneous_d2":
            continue
        multiplier = bytes.fromhex(item["multiplier_y"])
        for row_record in item["target_rows"]:
            row = bytes.fromhex(row_record[0])
            if len(row) == 5:
                target_y5_rows.add(row)
            elif len(row) == 4:
                target_y4_rows.add(row)
        if len(multiplier) == 1:
            y5_seeds.add((item["source_code"], multiplier))
    require(len(y5_seeds) == 16, "y5-stage seed census changed")
    y5_columns, y5_rows, y5_column_to_rows, y5_row_to_columns = close_top_layer(
        y5_seeds, originals, top_term_to_codes, 1
    )
    y5_singletons, y5_residual_columns = singleton_column_peel(
        y5_column_to_rows, y5_row_to_columns
    )
    y5_pivots, y5_dependent = exact_top_echelon(y5_columns, originals)
    require(len(y5_pivots) + len(y5_dependent) == len(y5_columns),
            "y5 echelon rank accounting changed")
    require((not y5_dependent) == (not y5_residual_columns),
            "singleton/echelon y5 independence guards disagree")
    y5_target_pivots = sorted(set(y5_pivots) & target_y5_rows)
    require(not y5_dependent and not y5_target_pivots,
            "the target-rooted y5 t-module gained a kernel or target pivot")

    record = {
        "format": "n8-orbit26-y10-d6-staged-top-closure-v1",
        "status": "EXACT_TARGET_STANDARD_THROUGH_TOTAL_D6",
        "seed_columns": len(seeds),
        "seed_target_rows": len(set().union(*seed_target_rows.values())),
        "original_top_occurrences": top_occurrences,
        "closed_y6_columns": len(columns),
        "closed_y6_rows": len(rows),
        "connected_components": len(components),
        "singleton_pivot_columns": len(pivot_ledger),
        "singleton_residual_columns": len(residual_columns),
        "component_profiles": [
            {
                "columns": len(component_columns),
                "rows": len(component_rows),
                "seeds": seed_count,
                "lex_column": [min(component_columns)[0],
                               min(component_columns)[1].hex()],
                "lex_row": min(component_rows).hex(),
            }
            for component_columns, component_rows, seed_count in components
        ],
        "column_digest": sha256(b"".join(
            code.to_bytes(2, "big") + multiplier
            for code, multiplier in sorted(columns)
        )).hexdigest(),
        "row_digest": sha256(b"".join(sorted(rows))).hexdigest(),
        "singleton_pivot_digest": sha256(b"".join(
            code.to_bytes(2, "big") + multiplier + row
            for (code, multiplier), row in pivot_ledger
        )).hexdigest(),
        "y5_stage": {
            "seed_columns": len(y5_seeds),
            "closed_columns": len(y5_columns),
            "closed_rows": len(y5_rows),
            "singleton_pivot_columns": len(y5_singletons),
            "singleton_residual_columns": len(y5_residual_columns),
            "exact_rank": len(y5_pivots),
            "kernel_dimension": len(y5_dependent),
            "incident_target_y5_rows": len(target_y5_rows),
            "target_pivot_rows": [row.hex() for row in y5_target_pivots],
            "column_digest": sha256(b"".join(
                code.to_bytes(2, "big") + multiplier
                for code, multiplier in sorted(y5_columns)
            )).hexdigest(),
            "pivot_digest": sha256(b"".join(sorted(y5_pivots))).hexdigest(),
        },
        "incident_target_y4_rows": len(target_y4_rows),
        "completed_lower_leads": {
            "original_d4_dividing_target": 0,
            "complete_d5_dividing_target": 0,
        },
        "theorem": (
            "The target-rooted t-free y2 packet has an exact 790-step singleton "
            "pivot ledger and therefore no y6 kernel. Hence no column touching a "
            "target y5*t or y4*t^2 divisor can survive from that packet. The remaining "
            "y1*t module is t times the completed degree-five module (the direct "
            "target-rooted closure has exact rank 22, kernel zero, and no target "
            "pivot), while the y0*t^2 module is t^2 times the original degree-four "
            "module. Since no completed d4 or d5 lead divides the target, no "
            "homogeneous degree-six initial monomial divides y10*t^2."
        ),
        "scope": (
            "exact target-specific standardness through total degree six for the "
            "frozen deterministic chart26 t-last order; it does not decide degree "
            "seven or alternative term orders/right inverses"
        ),
        "source_sha256": sha256(FIRST_PATH.read_bytes()).hexdigest(),
    }
    encoded = json.dumps(record, sort_keys=True, separators=(",", ":"))
    record["logical_sha256"] = sha256(encoded.encode("ascii")).hexdigest()
    RESULTS.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    print("y10 d6 staged y6 closure: PASS")
    print("seeds/columns/rows/components:", len(seeds), len(columns), len(rows),
          len(components))
    print("largest:", [(len(c), len(r), s) for c, r, s in components[:5]])
    print("singleton pivots/residual:", len(pivot_ledger),
          len(residual_columns))
    print("y5 seeds/columns/rows/rank/kernel/target-pivots:",
          len(y5_seeds), len(y5_columns), len(y5_rows), len(y5_pivots),
          len(y5_dependent), len(y5_target_pivots))
    print("logical sha256:", record["logical_sha256"])


if __name__ == "__main__":
    main()
