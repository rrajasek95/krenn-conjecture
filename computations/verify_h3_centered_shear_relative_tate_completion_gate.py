def require(condition: bool, detail: object) -> None:
    if not condition:
        raise RuntimeError(detail)


def pin_dependencies() -> None:
    for relative, expected in PINS.items():
        actual = sha256((ROOT / relative).read_bytes()).hexdigest()
        require(actual == expected,
                ("pinned dependency changed", relative, actual, expected))


def perfect_matchings(vertices):
    vertices = tuple(sorted(vertices))
    if not vertices:
        yield ()
        return
    first = vertices[0]
    for index, second in enumerate(vertices[1:], start=1):
        rest = vertices[1:index] + vertices[index + 1:]
        for tail in perfect_matchings(rest):
            yield tuple(sorted(((first, second),) + tail))


def occurrence_data():
    occurrences = []
    for p_site in range(6):
        for s_site in range(6):
            if p_site == s_site:
                continue
            residual = tuple(site for site in range(6)
                             if site not in (p_site, s_site))
            for matching in perfect_matchings(residual):
                occurrences.append((p_site, s_site, matching))
    require(len(occurrences) == len(set(occurrences)) == N,
            "the occurrence inventory changed")

    variables = (
        tuple(("p", site) for site in range(6))
        + tuple(("s", site) for site in range(6))
        + tuple(("q", left, right)
                for left in range(6) for right in range(left + 1, 6))
    )
    variable_index = {variable: index
                      for index, variable in enumerate(variables)}
    exponents = []
    for p_site, s_site, matching in occurrences:
        exponent = [0] * len(variables)
        exponent[variable_index[("p", p_site)]] = 1
        exponent[variable_index[("s", s_site)]] = 1
        for left, right in matching:
            exponent[variable_index[("q", left, right)]] += 1
        exponents.append(tuple(exponent))
    return tuple(occurrences), tuple(variables), tuple(exponents)


def rank(columns) -> int:
    if not columns:
        return 0
    height = len(columns[0])
    require(all(len(column) == height for column in columns), "rank width")
    rows = [[Q(columns[column][row]) for column in range(len(columns))]
            for row in range(height)]
    answer = 0
    for column in range(len(columns)):
        pivot = next((row for row in range(answer, height)
                      if rows[row][column]), None)
        if pivot is None:
            continue
        rows[answer], rows[pivot] = rows[pivot], rows[answer]
        pivot_value = rows[answer][column]
        rows[answer] = [value / pivot_value for value in rows[answer]]
        for row in range(height):
            if row == answer or not rows[row][column]:
                continue
            coefficient = rows[row][column]
            rows[row] = [left - coefficient * right
                         for left, right in
                         zip(rows[row], rows[answer], strict=True)]
        answer += 1
    return answer


def exponent_sum(exponents, indices):
    return tuple(sum(exponents[index][coordinate] for index in indices)
                 for coordinate in range(len(exponents[0])))


def quadratic_fibres(exponents):
    fibres = defaultdict(list)
    for pair in combinations_with_replacement(range(N), 2):
        fibres[exponent_sum(exponents, pair)].append(pair)
    return fibres


def degree_two_audit(exponents) -> tuple[dict[str, object], dict[tuple[int, int], tuple[int, int]]]:
    semigroup_rank = rank(exponents)
    height = N - semigroup_rank
    fibres = quadratic_fibres(exponents)
    source_monomials = comb(N + 1, 2)
    relation_dimension = source_monomials - len(fibres)
    profile = Counter(len(fibre) for fibre in fibres.values())
    require(semigroup_rank == 20 and height == 70
            and source_monomials == 4095
            and len(fibres) == 3870
            and relation_dimension == 225
            and profile == {1: 3645, 2: 225},
            ("the quadratic toric census changed",
             semigroup_rank, height, relation_dimension, profile))

    replacements = {}
    for fibre in fibres.values():
        if len(fibre) != 2:
            continue
        left, right = fibre
        replacements[left] = right
        replacements[right] = left
    require(len(replacements) == 450,
            "the quadratic replacement inventory changed")
    return ({
        "physical_coefficient_variables": 27,
        "occurrence_generators": N,
        "semigroup_rank": semigroup_rank,
        "toric_ideal_height": height,
        "quadratic_source_monomials": source_monomials,
        "distinct_physical_quadratic_images": len(fibres),
        "minimal_independent_quadratic_relations": relation_dimension,
        "quadratic_fibre_profile": {
            str(size): multiplicity
            for size, multiplicity in sorted(profile.items())
        },
        "complete_intersection": False,
        "non_CI_witness": "mu(I)>=225>height(I)=70",
    }, replacements)


def degree_three_audit(occurrences, exponents, replacements) -> dict[str, object]:
    fibres = defaultdict(list)
    for triple in combinations_with_replacement(range(N), 3):
        fibres[exponent_sum(exponents, triple)].append(triple)
    source_monomials = comb(N + 2, 3)
    ideal_dimension = source_monomials - len(fibres)
    profile = Counter(len(fibre) for fibre in fibres.values())

    total_components = 0
    disconnected = []
    for signature, vertices in fibres.items():
        lookup = {vertex: index for index, vertex in enumerate(vertices)}
        parent = list(range(len(vertices)))

        def find(index):
            while parent[index] != index:
                parent[index] = parent[parent[index]]
                index = parent[index]
            return index

        def union(left, right):
            left = find(left)
            right = find(right)
            if left != right:
                parent[right] = left

        for vertex_index, vertex in enumerate(vertices):
            for left, right, remaining in ((0, 1, 2), (0, 2, 1), (1, 2, 0)):
                pair = tuple(sorted((vertex[left], vertex[right])))
                if pair not in replacements:
                    continue
                target = tuple(sorted(replacements[pair] + (vertex[remaining],)))
                if target in lookup:
                    union(vertex_index, lookup[target])
        components = len({find(index) for index in range(len(vertices))})
        total_components += components
        if components > 1:
            disconnected.append((signature, tuple(vertices), components))

    quadratic_ideal_degree_three_rank = source_monomials - total_components
    new_cubic_generators = total_components - len(fibres)
    linear_quadratic_syzygies = (
        N * 225 - quadratic_ideal_degree_three_rank
    )
    disconnected_profile = Counter(
        (len(vertices), components)
        for _, vertices, components in disconnected
    )
    require(source_monomials == 125580
            and len(fibres) == 100520
            and ideal_dimension == 25060
            and quadratic_ideal_degree_three_rank == 19900
            and new_cubic_generators == 5160
            and linear_quadratic_syzygies == 350
            and disconnected_profile == {(2, 2): 5160},
            ("the cubic toric census changed", source_monomials,
             len(fibres), ideal_dimension,
             quadratic_ideal_degree_three_rank,
             new_cubic_generators, linear_quadratic_syzygies,
             disconnected_profile))

    # Freeze the lexicographically first quadratic-disconnected cubic fibre.
    first = min(disconnected, key=lambda item: item[1])
    _, vertices, components = first
    require(vertices == ((0, 4, 13), (1, 3, 14)) and components == 2,
            ("the first primitive cubic changed", vertices, components))
    require(exponent_sum(exponents, vertices[0])
            == exponent_sum(exponents, vertices[1]),
            "the primitive cubic stopped being a physical relation")
    explicit_occurrences = {
        str(index): [
            occurrences[index][0],
            occurrences[index][1],
            [list(edge) for edge in occurrences[index][2]],
        ]
        for index in sorted(set(vertices[0] + vertices[1]))
    }
    return {
        "cubic_source_monomials": source_monomials,
        "distinct_physical_cubic_images": len(fibres),
        "full_toric_I3_dimension": ideal_dimension,
        "quadratic_ideal_degree_three_rank": quadratic_ideal_degree_three_rank,
        "new_minimal_cubic_generators": new_cubic_generators,
        "linear_syzygies_among_225_quadrics": linear_quadratic_syzygies,
        "quadratic_disconnected_fibre_profile": {
            f"size_{size}_components_{components}": multiplicity
            for (size, components), multiplicity
            in sorted(disconnected_profile.items())
        },
        "first_primitive_cubic": "u0*u4*u13-u1*u3*u14",
        "first_primitive_cubic_occurrences": explicit_occurrences,
        "first_primitive_cubic_directional_derivative": (
            "k3=u4*u13+u0*u13+u0*u4-u3*u14-u1*u14-u1*u3"
        ),
        "first_primitive_cubic_shear_defect": "-L*k3",
        "first_primitive_cubic_relative_filler": "-epsilon*k3",
    }


