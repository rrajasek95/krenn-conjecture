"""Audit the relative Tate completion of the centered occurrence shear.

Let ``S=k[u_M]`` be the polynomial algebra on the ninety formal occurrence
coordinates and let ``A=S/I`` be their physical monomial image in
``k[p,s,q]``.  The centered shear derivation is

    delta_0(u_M)=-L,       L=z^T u,       1^T z=0.

It does not preserve ``I``.  On a relation ``r`` its defect is
``delta_0(r)=-L*partial_1(r)``, where
``partial_1=sum_M partial/partial u_M``.  After adjoining the *relative*
Koszul/Tate cell ``epsilon`` with ``d epsilon=L``, set

    delta(e_r)=-epsilon*partial_1(r)

for a degree-one Tate generator ``d e_r=r``.  This cancels every relation
defect, not only the first quadratic minor.

Because A is a toric domain and L is nonzero, L is A-regular.  Therefore a
semi-free resolution Q of A satisfies

    H_i(Q tensor K(L)) = 0 for i>0.

At every later Tate generator, the failure of ``[d,delta]=0`` is a positive
degree cycle and hence has a filler.  This gives a noncanonical recursive
homotopy-coherent lift over k and over k[beta].  It is a relative extension
resolving A/(L), not a quasi-isomorphic strict lift of A itself.

The checker also measures why this is not a finite Koszul source theorem.
The occurrence semigroup has rank 20, so I has height 70, while its minimal
quadratic relation space already has dimension 225.  In internal degree 3
there are 5160 additional binomials not generated by the quadrics, plus 350
linear syzygies among the quadratic generators.  The algebra is not a
complete intersection; its minimal commutative Tate/acyclic closure is
infinite.  The first explicit quadratic-disconnected cubic fibre is

    u_0*u_4*u_13-u_1*u_3*u_14=0.

Its shear defect is again ``-L*partial_1(r_3)`` and is filled by the same
epsilon formula.  Thus there is no new abstract obstruction beyond the
relative comparison cell, but there is no finite explicit physical cell
package supplied by formal Tate recursion either.
"""

