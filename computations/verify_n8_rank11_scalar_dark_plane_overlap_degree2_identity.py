def source_row_records():
    internal = {}
    for u, v in combinations(range(6), 2):
        for a, b in product(range(3), repeat=2):
            word = [-1] * 6
            word[u], word[v] = a, b
            internal[tuple(word)] = G.coefficient(u, v, a, b)
    internal2 = G.emultiply(internal, internal)
    internal3 = G.emultiply(internal2, internal)
    records = []
    for i, j in product(range(3), repeat=2):
        direct = G.coefficient(6, 7, i, j)
        response = {}
        for u, v in combinations(range(6), 2):
            for a, b in product(range(3), repeat=2):
                word = [-1] * 6
                word[u], word[v] = a, b
                value = G.padd(
                    G.pmultiply(G.coefficient(6, u, i, a),
                                G.coefficient(7, v, j, b)),
                    G.pmultiply(G.coefficient(6, v, i, b),
                                G.coefficient(7, u, j, a)),
                )
                if value:
                    response[tuple(word)] = value
        equation = G.eadd(
            G.escale(G.pscale(Q(1, 6), direct), internal3),
            G.escale({(): Q(1, 2)}, G.emultiply(response, internal2)),
        )
        if i == j:
            target = tuple([i] * 6)
            equation[target] = G.padd(
                equation.get(target, {}), {(): Q(-1)})
        records.extend(((i, j, word), row) for word, row in equation.items())
    return records


