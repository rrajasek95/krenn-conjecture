def jacobian_kernel_basis(rows, columns, width):
    """Deterministic exact echelon basis of ker(columns)."""

    pivots = {}
    for word in rows:
        row = {
            column: values[word]
            for column, values in columns.items() if word in values
        }
        while row:
            pivot = min(row)
            if pivot not in pivots:
                scale = row[pivot]
                pivots[pivot] = {
                    column: value / scale for column, value in row.items()
                }
                break
            scale = row[pivot]
            old = pivots[pivot]
            for column, value in old.items():
                row[column] = row.get(column, Fraction(0)) - scale * value
                if not row[column]:
                    del row[column]

    free = tuple(column for column in range(width) if column not in pivots)
    basis = []
    for free_column in free:
        vector = {free_column: Fraction(1)}
        for pivot in sorted(pivots, reverse=True):
            value = -sum(
                coefficient * vector.get(column, Fraction(0))
                for column, coefficient in pivots[pivot].items()
                if column != pivot
            )
            if value:
                vector[pivot] = value
        basis.append(vector)
    return free, tuple(basis)


def physical_hasse_column(oo, source, left_cell, right_cell):
    """Coefficient of st after varying two distinct physical cells."""

    u, v, a, b = left_cell
    x, y, c, d = right_cell
    if len({u, v, x, y}) < 4:
        return {}
    residual = tuple(site for site in range(8)
                     if site not in (u, v, x, y))
    output = defaultdict(Fraction)
    for matching in oo.perfect_matchings(residual):
        choices = []
        for first, second in matching:
            available = [
                (i, j, coefficient)
                for i in range(3) for j in range(3)
                if (coefficient := oo.entry(
                    source, first, second, i, j
                ))
            ]
            if not available:
                choices = []
                break
            choices.append(available)
        if not choices:
            continue
        for selected in product(*choices):
            word = [None] * 8
            word[u], word[v] = a, b
            word[x], word[y] = c, d
            coefficient = Fraction(1)
            for (first, second), (i, j, value) in zip(
                    matching, selected, strict=True):
                word[first], word[second] = i, j
                coefficient *= value
            output[tuple(word)] += coefficient
    return {word: value for word, value in output.items() if value}


def direction_hasse_column(left, right, same, physical_hasse):
    """Hasse coefficient for one square or one cross parameter monomial."""

    output = defaultdict(Fraction)
    support = sorted(set(left) | set(right))
    for first, second in combinations(support, 2):
        coefficient = left.get(first, Fraction(0)) * right.get(
            second, Fraction(0)
        )
        if not same:
            coefficient += left.get(second, Fraction(0)) * right.get(
                first, Fraction(0)
            )
        if not coefficient:
            continue
        for word, value in physical_hasse(first, second).items():
            output[word] += coefficient * value
    return {word: value for word, value in output.items() if value}


