def require(condition: bool, message: object) -> None:
    if not condition:
        raise RuntimeError(message)


def load(relative: str, name: str):
    specification = importlib.util.spec_from_file_location(name, ROOT / relative)
    require(specification is not None and specification.loader is not None,
            ("cannot import", relative))
    module = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(module)
    return module


def add(*columns):
    return tuple(sum((Q(column[row]) for column in columns), Q(0))
                 for row in range(ROWS))


def scale(value, column):
    return tuple(Q(value) * Q(entry) for entry in column)


def dot(left, right):
    return sum((Q(a) * Q(b) for a, b in zip(left, right, strict=True)), Q(0))


def rank(columns):
    if not columns:
        return 0
    work = [[Q(columns[column][row]) for column in range(len(columns))]
            for row in range(ROWS)]
    pivot_row = 0
    for column in range(len(columns)):
        pivot = next((row for row in range(pivot_row, len(work))
                      if work[row][column]), None)
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        value = work[pivot_row][column]
        work[pivot_row] = [entry / value for entry in work[pivot_row]]
        for row in range(len(work)):
            if row == pivot_row or not work[row][column]:
                continue
            value = work[row][column]
            work[row] = [left - value * right for left, right in
                         zip(work[row], work[pivot_row], strict=True)]
        pivot_row += 1
    return pivot_row


def vector(lower=(), ainc=0, w=(), target=(), ores=()):
    answer = [Q(0)] * ROWS
    for index, value in enumerate(lower):
        answer[LOWER.start + index] = Q(value)
    answer[AINC] = Q(ainc)
    for section, values in ((W, w), (TARGET, target), (ORES, ores)):
        for index, value in enumerate(values):
            answer[section.start + index] = Q(value)
    return tuple(answer)


def unit(index):
    return tuple(Q(int(position == index)) for position in range(N))


def target_action(values):
    answer = [Q(0)] * N
    for index, value in enumerate(values):
        answer[TARGET_ACTION[index]] += Q(value)
    return tuple(answer)


