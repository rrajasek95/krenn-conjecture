def hnf_with_transform(mat: List[List[int]], pivot_cols: int):
    """Row-style HNF on the first `pivot_cols` columns.

    Returns (H, U) with U * mat == H and U unimodular over Z.
    """
    m = len(mat)
    n = len(mat[0]) if m else 0
    H = [row[:] for row in mat]
    U = [[1 if i == j else 0 for j in range(m)] for i in range(m)]
    row = 0
    for col in range(pivot_cols):
        # find a pivot by repeated gcd elimination
        while True:
            nz = [r for r in range(row, m) if H[r][col] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda r: abs(H[r][col]))
            p = nz[0]
            for r in nz[1:]:
                q = H[r][col] // H[p][col]
                if q:
                    for c in range(n):
                        H[r][c] -= q * H[p][c]
                    for c in range(m):
                        U[r][c] -= q * U[p][c]
        nz = [r for r in range(row, m) if H[r][col] != 0]
        if not nz:
            continue
        p = nz[0]
        H[row], H[p] = H[p], H[row]
        U[row], U[p] = U[p], U[row]
        if H[row][col] < 0:
            H[row] = [-x for x in H[row]]
            U[row] = [-x for x in U[row]]
        row += 1
    return H, U


def integer_kernel_basis(B: List[List[int]], ncols: int) -> List[List[int]]:
    """A Z-basis of { x in Z^ncols : B x^T = 0 }, B given as rows over vertices."""
    # rows of Bt are the columns of B (one per edge)
    Bt = [[B[r][c] for r in range(len(B))] for c in range(ncols)]
    aug = [Bt[i] + [1 if i == j else 0 for j in range(ncols)] for i in range(ncols)]
    H, _ = hnf_with_transform(aug, len(B))
    basis = []
    for row in H:
        if all(x == 0 for x in row[: len(B)]):
            vec = row[len(B) :]
            if any(vec):
                basis.append(vec)
    return basis


def rank_q(mat: List[List[int]]) -> int:
    rows = [[Fraction(x) for x in r] for r in mat]
    if not rows:
        return 0
    n = len(rows[0])
    rank = 0
    for col in range(n):
        piv = next((r for r in range(rank, len(rows)) if rows[r][col]), None)
        if piv is None:
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        pv = rows[rank][col]
        for r in range(len(rows)):
            if r != rank and rows[r][col]:
                f = rows[r][col] / pv
                rows[r] = [rows[r][c] - f * rows[rank][c] for c in range(n)]
        rank += 1
    return rank


def solve_in_basis(vec: List[int], basis: List[List[int]]) -> Optional[List[int]]:
    """Express vec as an integer combination of the rows of `basis`."""
    r = len(basis)
    if r == 0:
        return [] if not any(vec) else None
    n = len(vec)
    # pick r independent columns
    cols = []
    for c in range(n):
        trial = cols + [c]
        sub = [[row[c2] for c2 in trial] for row in basis]
        if rank_q(sub) == len(trial):
            cols = trial
        if len(cols) == r:
            break
    if len(cols) < r:
        return None
    A = [[Fraction(basis[i][c]) for i in range(r)] for c in cols]  # r x r
    b = [Fraction(vec[c]) for c in cols]
    # gaussian elimination
    for i in range(r):
        piv = next((k for k in range(i, r) if A[k][i]), None)
        if piv is None:
            return None
        A[i], A[piv] = A[piv], A[i]
        b[i], b[piv] = b[piv], b[i]
        pv = A[i][i]
        A[i] = [x / pv for x in A[i]]
        b[i] = b[i] / pv
        for k in range(r):
            if k != i and A[k][i]:
                f = A[k][i]
                A[k] = [A[k][j] - f * A[i][j] for j in range(r)]
                b[k] = b[k] - f * b[i]
    coeffs = []
    for x in b:
        if x.denominator != 1:
            return None
        coeffs.append(int(x))
    # verify
    for c in range(n):
        if sum(coeffs[i] * basis[i][c] for i in range(r)) != vec[c]:
            return None
    return coeffs


def lattice_index(sub_gens: List[List[int]], basis: List[List[int]]) -> Optional[int]:
    """[ <basis> : <sub_gens> ] when both have the same rank; None if not."""
    r = len(basis)
    if r == 0:
        return 1 if not any(any(g) for g in sub_gens) else None
    coeff = []
    for g in sub_gens:
        c = solve_in_basis(g, basis)
        if c is None:
            return None
        coeff.append(c)
    if not coeff:
        return None
    if rank_q(coeff) != r:
        return None
    H, _ = hnf_with_transform(coeff, r)
    diag = []
    row = 0
    for col in range(r):
        if row < len(H) and H[row][col]:
            diag.append(abs(H[row][col]))
            row += 1
    if len(diag) != r:
        return None
    prod = 1
    for d in diag:
        prod *= d
    return prod


