def analyse_core(R: Sequence[int], A: Set[Edge]) -> Dict[str, object]:
    E = sorted(A)
    idx = {e: k for k, e in enumerate(E)}
    unit = {e: ONE for e in E}
    pms = supported_matchings(tuple(R), unit)
    assert pms
    B = [[1 if v in e else 0 for e in E] for v in R]
    frame = integer_kernel_basis(B, len(E))
    base = pms[0]
    gens = []
    for m in pms[1:]:
        vec = [0] * len(E)
        for e in base:
            vec[idx[e]] += 1
        for e in m:
            vec[idx[e]] -= 1
        gens.append(vec)
    bipartite = is_bipartite(R, A)
    beta = len(E) - len(R) + 1
    expected_rank = beta if bipartite else beta - 1
    flip_rank = rank_q(gens) if gens else 0
    out = {
        "n": len(R),
        "edges": len(E),
        "beta": beta,
        "bipartite": bipartite,
        "brick": (not bipartite) and is_brick(R, A),
        "perfect_matchings": len(pms),
        "frame_rank": len(frame),
        "expected_frame_rank": expected_rank,
        "flip_rank": flip_rank,
        "defect": len(frame) - flip_rank,
        "index": lattice_index(gens, frame) if (gens and flip_rank == len(frame)) else None,
    }
    return out


def is_three_connected(vertices: Sequence[int], edges: Set[Edge]) -> bool:
    vs = list(vertices)
    if len(vs) < 4:
        return False
    from u7h_core import components as _comp
    for u, v in combinations(vs, 2):
        rest = [x for x in vs if x != u and x != v]
        sub = {e for e in edges if e[0] in rest and e[1] in rest}
        if len(_comp(rest, sub)) != 1:
            return False
    return True


def is_bicritical(vertices: Sequence[int], edges: Set[Edge]) -> bool:
    """G - u - v has a perfect matching for every pair of distinct vertices."""
    vs = list(vertices)
    for u, v in combinations(vs, 2):
        rest = tuple(x for x in vs if x != u and x != v)
        sub = {e: ONE for e in edges if e[0] in rest and e[1] in rest}
        if not supported_matchings(rest, sub):
            return False
    return True


def is_brick(vertices: Sequence[int], edges: Set[Edge]) -> bool:
    """A brick: 3-connected and bicritical (hence matching covered)."""
    return is_three_connected(vertices, edges) and is_bicritical(vertices, edges)


def is_bipartite(vertices: Sequence[int], edges: Set[Edge]) -> bool:
    adj: Dict[int, List[int]] = {v: [] for v in vertices}
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    colour: Dict[int, int] = {}
    for s in vertices:
        if s in colour:
            continue
        colour[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for w in adj[u]:
                if w not in colour:
                    colour[w] = 1 - colour[u]
                    stack.append(w)
                elif colour[w] == colour[u]:
                    return False
    return True


