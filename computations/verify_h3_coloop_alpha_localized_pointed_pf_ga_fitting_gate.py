# Laurent monomials have exponent order (alpha,d,C,f,t).  Negative alpha
# exponents are allowed and no other negative exponent is used.
ZERO_EXP = (0, 0, 0, 0, 0)


def require(condition: bool, detail: object) -> None:
    if not condition:
        raise RuntimeError(detail)


def pin_dependencies() -> None:
    for relative, expected in PINS.items():
        actual = sha256((ROOT / relative).read_bytes()).hexdigest()
        require(actual == expected,
                ("pinned dependency changed", relative, actual, expected))


def clean(poly):
    return {monomial: Q(coefficient)
            for monomial, coefficient in poly.items() if coefficient}


def add(*polys):
    answer = {}
    for poly in polys:
        for monomial, coefficient in poly.items():
            answer[monomial] = answer.get(monomial, Q(0)) + coefficient
    return clean(answer)


def scale(poly, scalar):
    return clean({monomial: Q(scalar) * coefficient
                  for monomial, coefficient in poly.items()})


def multiply(left, right):
    answer = {}
    for left_monomial, left_coefficient in left.items():
        for right_monomial, right_coefficient in right.items():
            monomial = tuple(a+b for a, b in
                             zip(left_monomial, right_monomial, strict=True))
            answer[monomial] = answer.get(monomial, Q(0)) + (
                left_coefficient * right_coefficient
            )
    return clean(answer)


def constant(value):
    return {ZERO_EXP: Q(value)} if value else {}


def variable(index, exponent=1):
    powers = [0] * len(ZERO_EXP)
    powers[index] = exponent
    return {tuple(powers): Q(1)}


ALPHA, DIAGONAL, COFACTOR, SELECTED, PARAMETER = (
    variable(index) for index in range(5)
)
ALPHA_INV = variable(0, -1)
ONE = constant(1)


def quotient_coordinates(split: str, flowed: bool):
    """Images of the localized packet in k[a^+-1,d,C,f,t]."""
    f = add(SELECTED, PARAMETER) if flowed else SELECTED
    pure = add(ONE, scale(multiply(DIAGONAL, COFACTOR), -1))
    mixed = scale(multiply(ALPHA, COFACTOR), -1)
    aggregate = pure if split == "U" else mixed
    g = add(aggregate, scale(f, -1))
    return {
        "alpha": ALPHA,
        "alpha_inv": ALPHA_INV,
        "d": DIAGONAL,
        "C": COFACTOR,
        "Cc": ALPHA_INV,
        "U": pure,
        "V": mixed,
        "f": f,
        "g": g,
    }


def localized_relations(values, split):
    split_value = values[split]
    return {
        "alpha*alpha_inv-1": add(
            multiply(values["alpha"], values["alpha_inv"]), scale(ONE, -1)
        ),
        "alpha*Cc-1": add(
            multiply(values["alpha"], values["Cc"]), scale(ONE, -1)
        ),
        "d*C+U-1": add(
            multiply(values["d"], values["C"]), values["U"], scale(ONE, -1)
        ),
        "alpha*C+V": add(
            multiply(values["alpha"], values["C"]), values["V"]
        ),
        f"{split}-f-g": add(
            split_value, scale(values["f"], -1), scale(values["g"], -1)
        ),
    }


def localized_ga_audit(split):
    base = quotient_coordinates(split, flowed=False)
    flowed = quotient_coordinates(split, flowed=True)
    require(all(not polynomial for polynomial in
                localized_relations(base, split).values()),
            (split, "base parametrization failed"))
    require(all(not polynomial for polynomial in
                localized_relations(flowed, split).values()),
            (split, "translation stopped preserving the packet"))
    require(flowed["alpha"] == base["alpha"]
            and flowed["alpha_inv"] == base["alpha_inv"],
            "the occurrence translation moved the coloop localizer")

    # The monic equations eliminate alpha_inv,Cc,U,V,g successively.  What
    # remains is exactly k[alpha^+-1,d,C,f], and the flow translates f.
    return {
        "localized_quotient": "k[alpha^{+/-1},d,C,f]",
        "eliminated": ["alpha_inv", "Cc", "U", "V", "g"],
        "integrated_action": "f -> f+t, g -> g-t",
        "fixed_data": ["alpha", "alpha_inv", "d", "C", "Cc", "U", "V"],
        "P_f_on_infinitesimal_generator": 1,
        "relative_cotangent": "Omega(packet/aggregate base)=R*df, free rank 1",
        "ideal_status": "prime and proper Laurent-chart ideal; no source unit",
    }


def determinant(left, right):
    return Q(left[0]) * Q(right[1]) - Q(left[1]) * Q(right[0])


def fitting_audit():
    aggregate = (Q(1), Q(1))
    # Complete rows and every unit rescaling of them remain on the symmetric
    # line.  In particular alpha-localization does not add rank.
    symmetric_rows = ((Q(1), Q(1)), (Q(2), Q(2)), (Q(-3), Q(-3)))
    require(all(determinant(aggregate, row) == 0 for row in symmetric_rows),
            "a symmetric complete row became occurrence-transverse")

    # General exact criterion.  A physical row r=(r_f,r_g) raises the
    # two-occurrence rank precisely through r_g-r_f.
    candidates = ((0, 0), (1, 1), (2, -1), (-3, 5))
    minors = []
    for row in candidates:
        minor = determinant(aggregate, row)
        require(minor == Q(row[1]) - Q(row[0]),
                ("Fitting difference changed", row, minor))
        minors.append(str(minor))
    selected = (Q(1), Q(0))
    require(determinant(aggregate, selected) == -1,
            "a genuine pointed physical row stopped being a unit minor")
    return {
        "aggregate_occurrence_row": [1, 1],
        "transverse_minor_for_row_(r_f,r_g)": "r_g-r_f",
        "symmetric_complete_rows": "all minors zero, also after alpha rescaling",
        "relative_Fitt0": "(0) before an occurrence-asymmetric physical row",
        "unit_minor_if_P_f_is_physical": -1,
        "exact_exit_criterion": (
            "an additional physical full-source row has unequal f,g coefficients; "
            "after localization, a unit difference gives the source/Fitting exit"
        ),
        "sample_minors": minors,
    }


