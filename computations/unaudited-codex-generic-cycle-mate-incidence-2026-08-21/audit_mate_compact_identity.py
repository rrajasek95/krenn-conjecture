FORCED_Q = frozenset((0, 4, 5, 6, 8, 9, 10, 12, 13, 14, 15))
CHOSEN_Q = (0, 12, 5, 6)


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


CORE = load("generic_cycle_mate_compact_core", CORE_PATH)


def require(condition, detail):
    if not condition:
        raise RuntimeError(detail)


def clean(poly):
    return Counter({monomial: coefficient for monomial, coefficient in poly.items()
                    if coefficient})


def add(*polys):
    result = Counter()
    for poly in polys:
        result.update(poly)
    return clean(result)


def scale(poly, coefficient):
    return clean(Counter({monomial: coefficient*value
                          for monomial, value in poly.items()}))


def multiply(*polys):
    result = Counter({(): 1})
    for poly in polys:
        updated = Counter()
        for left, lc in result.items():
            for right, rc in poly.items():
                updated[tuple(sorted(left+right))] += lc*rc
        result = clean(updated)
    return result


def specialize(poly):
    return clean(Counter({monomial: coefficient
                          for monomial, coefficient in poly.items()
                          if not any(variable in ZERO_CELLS
                                     for variable in monomial)}))


def q(index):
    bits = tuple((index >> (3-site)) & 1 for site in range(4))
    return specialize(CORE.q_orientation(bits))


