    u = Counter({(u_index,): 1})
    one = Counter({(): 1})
    rabinowitsch = add(multiply(u, h), scale(one, -1))
    certificate = add(multiply(u, rhs), scale(rabinowitsch, -1))
    require(certificate == one, "compact mate-H unit failed")
