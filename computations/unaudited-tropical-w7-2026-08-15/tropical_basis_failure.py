def refine_and_verify(inst, z0, digits=60):
    """Newton in mpmath from the float solution; returns the final residual and
    the min/max cell modulus, all computed at `digits` precision."""
    mp.dps = digits
    monos, eq_of, rhs = inst.build()
    ncell = inst.ncell
    neq = len(rhs)
    groups = [[] for _ in range(neq)]
    for k, mono in enumerate(monos):
        groups[eq_of[k]].append(mono)
    z = [mpc(complex(v)) for v in z0]

    def residual(z):
        x = [mp.e ** zi for zi in z]
        out = []
        for e, terms in enumerate(groups):
            s = mpc(0)
            for mono in terms:
                p = mpc(1)
                for idx in mono:
                    p *= x[idx]
                s += p
            out.append(s - rhs[e])
        return out, x

    for _ in range(60):
        F, x = residual(z)
        nrm = max(abs(v) for v in F)
        if nrm < mp.mpf(10) ** (-digits + 12):
            break
        J = mpmatrix(neq, ncell)
        for e, terms in enumerate(groups):
            for mono in terms:
                p = mpc(1)
                for idx in mono:
                    p *= x[idx]
                for idx in mono:
                    J[e, idx] += p
        # normal equations (overdetermined): solve J^H J s = -J^H F
        JH = J.transpose_conj()
        A = JH * J
        for i in range(ncell):
            A[i, i] += mp.mpf(10) ** (-digits + 20)
        b = JH * mpmatrix(F)
        for i in range(ncell):
            b[i] = -b[i]
        try:
            step = lu_solve(A, b)
        except Exception:
            break
        z = [z[i] + step[i] for i in range(ncell)]
    F, x = residual(z)
    return {"residual": mp.nstr(max(abs(v) for v in F), 6),
            "min_abs_cell": mp.nstr(min(abs(v) for v in x), 8),
            "max_abs_cell": mp.nstr(max(abs(v) for v in x), 8),
            "digits": digits, "n_equations": neq}


