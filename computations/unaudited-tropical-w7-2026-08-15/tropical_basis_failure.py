def sweep(nsites=6, restarts=4, iters=200):
    data = build(nsites, verbose=False)
    from kill_engine2 import run as run2, verdict
    _, rows = run2(nsites)
    patterns = [("0", "0", "0"), ("-", "-", "-")]
    results = []
    for row in rows:
        openpats = [p for p in patterns if verdict(row, p, nsites) is None]
        if not openpats:
            continue
        for p in openpats:
            diag = tuple(0 if s == "0" else -1 for s in p)
            g = tuple(row["point"])
            inst = Instance(nsites, g, diag)
            rec = solve(inst, restarts=restarts, iters=iters,
                        seed=abs(hash((str(g), p))) % 9999)
            results.append({"dim": row["dim"],
                            "g": [str(c) for c in g], "sigma": "".join(p),
                            "status": rec["status"],
                            "eq_residual": rec.get("eq_residual"),
                            "min_abs_cell": rec.get("min_abs_cell")})
            print("   dim %d g=(%s,%s,%s) sigma=%s : %s (res %.2e)"
                  % (row["dim"], g[0], g[1], g[2], "".join(p),
                     rec["status"], rec.get("eq_residual", float("nan"))))
            sys.stdout.flush()
    return results


