def main():
    which = sys.argv[1] if len(sys.argv) > 1 else "6"
    out = {}
    for name, nsites, g, diag, note in CASES[which]:
        inst = Instance(nsites, g, diag)
        rec = solve(inst, restarts=(8 if nsites == 6 else 4),
                    iters=(250 if nsites == 6 else 150),
                    seed=abs(hash(name)) % 9999)
        tag = (" [%s]" % note) if note else ""
        print("%-46s%s\n     %s" % (name, tag, rec["status"]))
        for k in ("eq_residual", "min_abs_cell", "max_abs_cell",
                  "box_violation", "n_equations"):
            if k in rec:
                print("       %-15s %s" % (k, rec[k]))
        out[name] = rec
        sys.stdout.flush()
    with open("results_initial_probe_N%s.json" % which, "w") as h:
        json.dump(out, h, indent=1, default=str)
    print("wrote results_initial_probe_N%s.json" % which)


