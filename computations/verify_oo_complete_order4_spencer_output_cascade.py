# Sparse polynomials in kappa,Y for the final four-coordinate module.
KAPPA_INDEX, Y_INDEX = 0, 1


def poly_constant(value=1):
    value = Q(value)
    return {(0, 0): value} if value else {}


def poly_variable(index):
    exponent = [0, 0]
    exponent[index] = 1
    return {tuple(exponent): Q(1)}


def poly_add(*polynomials):
    answer = {}
    for polynomial in polynomials:
        for monomial, value in polynomial.items():
            answer[monomial] = answer.get(monomial, Q(0)) + value
            if not answer[monomial]:
                del answer[monomial]
    return answer


def poly_scale(scalar, polynomial):
    scalar = Q(scalar)
    return {monomial: scalar * value for monomial, value in polynomial.items()
            if scalar * value}


def poly_multiply(left, right):
    answer = {}
    for left_monomial, left_value in left.items():
        for right_monomial, right_value in right.items():
            monomial = (left_monomial[0] + right_monomial[0],
                        left_monomial[1] + right_monomial[1])
            answer[monomial] = answer.get(monomial, Q(0)) + (
                left_value * right_value
            )
            if not answer[monomial]:
                del answer[monomial]
    return answer


def vector_add(*vectors):
    return tuple(poly_add(*(vector[index] for vector in vectors))
                 for index in range(4))


def vector_scale(scalar, vector):
    return tuple(poly_scale(scalar, value) for value in vector)


def pairing(covector, vector):
    return poly_add(*(poly_multiply(left, right)
                      for left, right in zip(covector, vector, strict=True)))


def determinant(columns):
    require(len(columns) == 4 and all(len(column) == 4 for column in columns),
            "the determinant needs four four-coordinate columns")
    answer = {}
    for permutation in permutations(range(4)):
        inversions = sum(permutation[i] > permutation[j]
                         for i in range(4) for j in range(i + 1, 4))
        term = poly_constant(-1 if inversions % 2 else 1)
        for row, column in enumerate(permutation):
            term = poly_multiply(term, columns[column][row])
        answer = poly_add(answer, term)
    return answer


def evaluate(polynomial, kappa=1, y=1):
    return sum(value * Q(kappa) ** exponent[0] * Q(y) ** exponent[1]
               for exponent, value in polynomial.items())


def rational_rank(columns, kappa=1, y=1):
    rows = [[evaluate(column[row], kappa, y) for column in columns]
            for row in range(4)]
    rank = 0
    for column in range(len(columns)):
        pivot = next((row for row in range(rank, 4) if rows[row][column]), None)
        if pivot is None:
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        pivot_value = rows[rank][column]
        rows[rank] = [value / pivot_value for value in rows[rank]]
        for row in range(4):
            if row == rank or not rows[row][column]:
                continue
            factor = rows[row][column]
            rows[row] = [value - factor * lead
                         for value, lead in zip(rows[row], rows[rank])]
        rank += 1
    return rank


def encode_polynomial(polynomial):
    names = ("kappa", "Y")
    terms = []
    for exponent, value in sorted(polynomial.items()):
        factors = [str(value)]
        for name, power in zip(names, exponent, strict=True):
            if power:
                factors.append(name if power == 1 else f"{name}^{power}")
        terms.append("*".join(factors))
    return "+".join(terms) if terms else "0"


def audit_specialized_augmented_module():
    one = poly_constant()
    minus_one = poly_constant(-1)
    zero = {}
    y = poly_variable(Y_INDEX)
    kappa = poly_variable(KAPPA_INDEX)
    kappa_y = poly_multiply(kappa, y)

    # Coordinates: coefficient of u*e_Eq after edges=0, w, target, ores.
    # HYP-L gives F_alpha|_0=-target(g_alpha)*u, so every one of the
    # 6561 physical rows specializes to a multiple of physical_row.
    physical_row = (minus_one, zero, one, zero)
    cap_t = (zero, poly_scale(-1, y), one, zero)
    cap_rho = (zero, one, zero, one)
    # Every nonbottom Hasse/denominator readout with q-zero value carries
    # the exact Eq defect B=H0-u, hence u coefficient -1.
    top_with_eq_defect = (minus_one, y, zero, zero)
    desired = (zero, kappa_y, zero, zero)

    require(top_with_eq_defect
            == vector_add(physical_row, vector_scale(-1, cap_t)),
            "the q-zero top stopped being the physical-row/cap graph")
    physical_generators = [physical_row, cap_t, cap_rho, top_with_eq_defect]
    require(rational_rank(physical_generators, 1, 1) == 3,
            "the specialized physical module rank changed")
    require(rational_rank(physical_generators + [desired], 1, 1) == 4,
            "the desired class stopped raising rank 3 to 4")

    covector = (y, one, y, minus_one)
    require(all(not pairing(covector, column)
                for column in physical_generators),
            "the integral cokernel covector stopped killing a physical type")
    desired_pairing = pairing(covector, desired)
    require(desired_pairing == kappa_y and desired_pairing,
            "the cokernel covector stopped reading kappa*Y")
    det = determinant([physical_row, cap_t, cap_rho, desired])
    require(det == poly_scale(-1, kappa_y),
            "the augmented determinant stopped being -kappa*Y")

    # The formal prolonged top omits the Eq coordinate and is exactly the
    # desired column.  Its source-faithful diagonal projection adds the
    # top_with_eq_defect type, on which the covector vanishes.
    require(pairing(covector, top_with_eq_defect) == {}
            and pairing(covector, desired) == kappa_y,
            "the prolonged/physical distinction collapsed")

    return {
        "coordinates": ["u*Eq after edges=0", "w", "target", "ores"],
        "physical_type_columns": {
            "full_nine_target_row": ["-1", "0", "1", "0"],
            "T": ["0", "-Y", "1", "0"],
            "rho": ["0", "1", "0", "1"],
            "qzero_top_with_Eq_defect": ["-1", "Y", "0", "0"],
        },
        "physical_rank": 3,
        "rank_with_desired": 4,
        "desired": ["0", "kappa*Y", "0", "0"],
        "integral_cokernel_covector": ["Y", "1", "Y", "-1"],
        "desired_pairing": encode_polynomial(desired_pairing),
        "augmented_determinant": encode_polynomial(det),
        "formal_prolonged_top": "desired column, but not source-faithful",
        "physical_projection": "adds (-u)*Eq and lies in the rank-3 graph",
    }


