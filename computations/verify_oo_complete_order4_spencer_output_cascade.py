    for item in term:
        require(is_edge(item), "the mixed row acquired a non-edge variable")
        _tag, left, right, left_colour, right_colour = item
        degree[left][left_colour] += 1
        degree[right][right_colour] += 1
    return tuple(tuple(row) for row in degree)


