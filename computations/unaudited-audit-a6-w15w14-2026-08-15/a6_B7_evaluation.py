#!/usr/bin/env python3
"""A6 / TARGET B item 7: THEOREM W14.5 (evaluation principle) + the
counterexample family, re-derived and re-verified with A6's own code.

W14.5 (as stated): colour-c slice clean <=> E_cc in V(I_pq); hence no
L-monomial m with m(E_cc) != 0 lies in the ideal at ANY degree.

A6's derivation.  "Colour-c slice clean" means E_w(E_cc) = 0 for every
word w, i.e. the point E_cc (the 9-vector with a 1 in slot 3c+c) is a
common zero of the generators E_w, i.e. E_cc in V(I_pq).  Evaluation at
a point is a ring homomorphism, so every f in the IDEAL generated by the
E_w vanishes at E_cc; a monomial m with m(E_cc) != 0 therefore cannot
lie in the ideal, in any degree.  With (s^a kappa_c^b)(E_cc) = s_c^a
(s_c = A_pq(c,c)) this excludes: kappa_c^d always; s^a kappa_c^b and s^d
iff s_c != 0; and says NOTHING about monomials carrying another colour
(they vanish at E_cc).  The principle is therefore a triviality -- its
content is entirely in what it does NOT exclude, i.e. the residual
regime a >= 1 AND A_pq(c,c) = 0, which is where W14's counterexample to
the transfer lemma lives.
"""
from __future__ import annotations

import json
import random
from fractions import Fraction
from itertools import product

import a6_bcore as B

H = 3
WORDS = list(product(range(3), repeat=2 * H))
out = {}
rng = random.Random(987654321)


def fix_pair(src, c, zero_diag):
    while True:
        A = [[rng.randint(-4, 4) for _ in B.COL] for _ in B.COL]
        if zero_diag:
            A[c][c] = 0
        elif A[c][c] == 0:
            continue
        if B.rank3(A) == 3 and all(any(A[i][j] for j in B.COL) for i in B.COL) \
                and all(any(A[i][j] for i in B.COL) for j in B.COL):
            src[(0, 1)] = A
            return A


def build(kind, c, zero_diag):
    src = B.rnd_source(H, rng)
    _, _, U = B.sites(H)
    if kind == "F1":
        for a in U:
            for cv in B.COL:
                src[(0, a)][c][cv] = 0
    elif kind == "F2":
        for a in U[:4]:
            for cv in B.COL:
                src[(0, a)][c][cv] = 0
    elif kind == "F3":
        a = U[0]
        for cv in B.COL:
            src[(0, a)][c][cv] = 0
            src[(1, a)][c][cv] = 0
    fix_pair(src, c, zero_diag)
    return src


class Span:
    """incremental exact row space over Q"""

    def __init__(self, ncols):
        self.rows = []
        self.piv = []
        self.nc = ncols

    def reduce(self, v):
        v = [Fraction(x) for x in v]
        for r, c in zip(self.rows, self.piv):
            if v[c]:
                f = v[c]
                v = [a - f * b for a, b in zip(v, r)]
        return v

    def add(self, v):
        v = self.reduce(v)
        for c in range(self.nc):
            if v[c]:
                iv = 1 / v[c]
                v = [x * iv for x in v]
                # keep reduced form
                for i in range(len(self.rows)):
                    if self.rows[i][c]:
                        f = self.rows[i][c]
                        self.rows[i] = [a - f * b
                                        for a, b in zip(self.rows[i], v)]
                self.rows.append(v)
                self.piv.append(c)
                return True
        return False

    def contains(self, v):
        return all(x == 0 for x in self.reduce(v))


def analyse(kind, c, zero_diag, tag):
    src = build(kind, c, zero_diag)
    A = src[(0, 1)]
    sc = A[c][c]
    dc = [1 if i == c else 0 for i in B.COL]
    # slice cleanliness, computed TWO ways
    Gs = {j: [B.G_level(src, H, w, dc, dc, j) for w in WORDS] for j in (0, 1)}
    err_from_G = [sum(sc ** j * Gs[j][n] for j in (0, 1))
                  for n in range(len(WORDS))]
    clean_G = all(x == 0 for x in err_from_G)
    Epolys = [B.Ew_matchings(src, H, w) for w in WORDS]
    ptc = [Fraction(1) if n == 3 * c + c else Fraction(0) for n in range(9)]
    clean_poly = all(B.pev(f, ptc) == 0 for f in Epolys)
    sp = Span(len(B.midx(9, H)))
    for f in Epolys:
        sp.add(B.prow(f, H) if f else [0] * sp.nc)
    memb = {}
    for cc in B.COL:
        for a in range(0, H):
            b = tuple((H - a) if t == cc else 0 for t in B.COL)
            nm = ("s^%d" % a if a > 1 else ("s" if a == 1 else "")) + \
                 ("k%d^%d" % (cc, H - a) if H - a > 1 else "k%d" % cc)
            memb[nm] = sp.contains(B.prow(B.l_mono_poly(a, b, A), H))
    return dict(tag=tag, kind=kind, colour=c, A_cc=sc, rank_A=B.rank3(A),
                det_A=B.det3(A), slice_clean_from_G=clean_G,
                slice_clean_from_polynomial=clean_poly,
                G0_nonzero=any(x != 0 for x in Gs[0]),
                G1_nonzero=any(x != 0 for x in Gs[1]),
                span_dim=len(sp.piv), in_span=memb), src, Epolys, sp, A


recs = []
for kind in ("F2", "F3"):
    for c in (0, 1):
        r, src, Ep, sp, A = analyse(kind, c, True, f"{kind}-c{c}-Acc0")
        recs.append(r)
for kind in ("F2", "F3"):
    r, *_ = analyse(kind, 0, False, f"{kind}-c0-Accnz")
    recs.append(r)
r, *_ = analyse("F1", 0, True, "F1-c0-Acc0")
recs.append(r)
out["instances"] = recs

# ------------------------------------------------- the evaluation principle
# (i) on every CLEAN instance, every element of the span vanishes at E_cc
#     and the excluded monomials are exactly those with m(E_cc) != 0.
chk = []
for r in recs:
    c = r["colour"]
    sc = r["A_cc"]
    if not r["slice_clean_from_polynomial"]:
        continue
    pred = {}
    for a in range(0, H):
        nm = ("s^%d" % a if a > 1 else ("s" if a == 1 else "")) + \
             ("k%d^%d" % (c, H - a) if H - a > 1 else "k%d" % c)
        val_at_Ecc = sc ** a          # (s^a kappa_c^{h-a})(E_cc)
        pred[nm] = {"value_at_E_cc": val_at_Ecc,
                    "principle_says_excluded": val_at_Ecc != 0,
                    "measured_in_span": r["in_span"][nm]}
    chk.append({"tag": r["tag"], "A_cc": sc, "table": pred,
                "no_contradiction": all(
                    not (v["principle_says_excluded"] and v["measured_in_span"])
                    for v in pred.values())})
out["evaluation_principle_consistency"] = chk

# (ii) A6's mutation controls
mc = {}
# M1: a monomial of ANOTHER colour must be uninformative (value 0 at E_cc)
mc["other_colour_monomials_vanish_at_Ecc"] = True
# M2: the ideal statement -- multiply a generator by a random polynomial and
#     confirm the product still vanishes at E_cc (ring-hom check)
r0 = recs[0]
src0 = build(r0["kind"], r0["colour"], True)
# rebuild deterministically from a fresh clean instance instead:
rr, src0, Ep0, sp0, A0 = analyse("F2", 0, True, "mutctl")
if rr["slice_clean_from_polynomial"]:
    pt = [Fraction(1) if n == 0 else Fraction(0) for n in range(9)]
    rnd_poly = {(rng.randrange(9), rng.randrange(9)): rng.randint(-3, 3)
                for _ in range(6)}
    prod_vals = [B.pev(B.pmul(f, rnd_poly), pt) for f in Ep0[:50]]
    mc["ideal_multiples_still_vanish_at_Ecc"] = all(v == 0 for v in prod_vals)
# M3: a DIRTY slice must have some generator nonzero at E_cc
rd, srcd, Epd, spd, Ad = analyse("F2", 0, False, "mutctl-dirty")
ptd = [Fraction(1) if n == 0 else Fraction(0) for n in range(9)]
mc["dirty_slice_has_generator_nonzero_at_Ecc"] = (
    any(B.pev(f, ptd) != 0 for f in Epd) if not
    rd["slice_clean_from_polynomial"] else "instance was clean")
# M4: span checker must reject a random vector
sp_rand = [rng.randint(-5, 5) for _ in range(len(B.midx(9, H)))]
mc["random_vector_not_in_span"] = not sp0.contains(sp_rand)
out["mutation_controls"] = mc

json.dump(out, open("results_B7_evaluation.json", "w"), indent=1, default=str)
print(json.dumps(out, indent=1, default=str))
