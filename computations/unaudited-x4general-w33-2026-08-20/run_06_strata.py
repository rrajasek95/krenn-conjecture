# ------------------------------------------------------------- kernel syzygy
def kernel_syzygy_control():
    """Ker_j is the space of linear syzygies of the partial hafnians.
    Checked by: (i) dim Ker_j >= 2 * #null r, with equality iff no
    nontrivial syzygy; (ii) every kernel vector, contracted against the
    partial hafnians, gives the zero polynomial."""
    res = {}
    tests = []
    src = cycle_pm_pair(N)
    tests.append(("delta2", src))
    P = [0, 2, 4, 6]
    s2 = cycle_pm_pair(N)
    import random
    rg = random.Random(606)
    for (u, v) in itertools.combinations(P, 2):
        for a in range(2):
            for b in range(2):
                s2[(u, v)][a][b] = Fraction(rg.randrange(1, 6))
    require(is_exact2(s2, N)[0], "all-P-chord source not exact")
    tests.append(("allP", s2))
    s3 = zero_source(N, 2)
    for (e, a, b), val in SC_POINT.items():
        s3[e][a][b] = Fraction(val)
    tests.append(("SC", s3))
    for name, B in tests:
        prof, nulls, checks = [], [], 0
        for j in range(N):
            dim, basis, cols, zcols = star_kernel(B, j, N)
            nz = sorted({r for (r, _d) in zcols})
            prof.append(dim)
            nulls.append(len(nz))
            # verify the syzygy identity for every basis vector
            for bv in basis:
                for u in itertools.product(range(2), repeat=N - 1):
                    VP = [x for x in range(N) if x != j]
                    wd = {VP[i]: u[i] for i in range(N - 1)}
                    tot = Fraction(0)
                    for i, (r, d) in enumerate(cols):
                        if wd[r] != d or bv[i] == 0:
                            continue
                        S = [x for x in range(N) if x not in (j, r)]
                        tot += bv[i] * haf(B, wd, sites=S)
                    require(tot == 0, f"syzygy identity fails: {name} j={j}")
                    checks += 1
        res[name] = {"kerprof": prof, "null_degrees": nulls,
                     "extra_syzygy_dims": [prof[j] - 2 * nulls[j]
                                           for j in range(N)],
                     "identity_checks": checks}
        print("  syzygy control", name, res[name]["kerprof"],
              "nulls", res[name]["null_degrees"],
              "extra", res[name]["extra_syzygy_dims"], flush=True)
    R["kernel_syzygy"] = res
    MAN.mark("kernel_syzygy")
    MAN.mark("explicit_points")


