def pm_all(sites):
    sites = tuple(sites)
    if not sites:
        return [()]
    h, rest = sites[0], sites[1:]
    out = []
    for i, x in enumerate(rest):
        for M in pm_all(rest[:i] + rest[i + 1:]):
            out.append(((h, x),) + M)
    return out


PMS = pm_all(range(N))


def sing_system(cells, extra_eq=()):
    """cells: ordered list of (edge, a, b).  Returns (gens, nv, names)."""
    cm = {}
    for i, (e, a, b) in enumerate(cells):
        cm[(e, a, b)] = f"zzv({i + 1})"
    gs = []
    for w in itertools.product(range(2), repeat=N):
        terms = []
        for M in PMS:
            mon, ok = [], True
            for (u, v) in M:
                e = (u, v) if u < v else (v, u)
                key = (e, w[u], w[v]) if u < v else (e, w[v], w[u])
                nm = cm.get(key)
                if nm is None:
                    ok = False
                    break
                mon.append(nm)
            if ok:
                terms.append("*".join(sorted(mon)))
        tgt = 1 if len(set(w)) == 1 else 0
        if not terms and tgt == 0:
            continue
        gs.append(f"({'+'.join(terms) if terms else '0'})-({tgt})")
    gs = sorted(set(gs)) + list(extra_eq)
    return gs, len(cells)


def sing_dim(gs, nv, sat=True, extra=""):
    prod = "*".join(f"zzv({i})" for i in range(1, nv + 1))
    script = (f"ring R = 0, (zzv(1..{nv}), zzt), dp;\n"
              "ideal zzI = " + ",\n ".join(gs) +
              (f",\n zzt*{prod}-1" if sat else "") + ";\n"
              "ideal zzG = std(zzI);\n"
              '"DIM:", dim(zzG);\n'
              '"UNIT:", (size(zzG) == 1 && zzG[1] == 1);\n'
              '"NGENS:", size(zzG);\n' + extra)
    no_shadow_guard(script, {"zzt"} | {f"zzv({i})" for i in range(1, nv + 1)})
    txt = run_singular(script, timeout=1800)
    out = {}
    for ln in txt.splitlines():
        ln = ln.strip()
        for k in ("DIM", "UNIT", "NGENS", "EQ", "NCOMP", "CDIMS"):
            if ln.startswith(k + ":"):
                out[k] = ln.split(":", 1)[1].strip()
    return out, txt


# ------------------------------------------------------------------ SA
def stratum_A():
    P = [0, 2, 4, 6]
    cells = []
    for i in range(N):
        u, v = i, (i + 1) % N
        a = i % 2
        cells.append(((min(u, v), max(u, v)), a, a))
    for (u, v) in itertools.combinations(P, 2):
        for a in range(2):
            for b in range(2):
                cells.append(((u, v), a, b))
    gs, nv = sing_system(cells)
    # the two PM-product binomials, in this variable order
    b0 = "*".join(f"zzv({i + 1})" for i in range(N) if i % 2 == 0) + "-1"
    b1 = "*".join(f"zzv({i + 1})" for i in range(N) if i % 2 == 1) + "-1"
    extra = (f"ideal zzB = {b0}, {b1};\n"
             "ideal zzGB = std(zzB);\n"
             '"EQ:", (size(reduce(zzI,zzGB)) == 0) && '
             "(size(reduce(zzB,zzG)) == 0);\n")
    out, _txt = sing_dim(gs, nv, sat=False, extra=extra)
    R["SA"] = {"n_cells": nv, "n_word_equations": len(gs), "dim": out["DIM"],
               "ideal_equals_two_binomials": out.get("EQ"),
               "gb_size": out["NGENS"]}
    require(out.get("EQ", "0").strip() in ("1", "TRUE", "true"),
            f"SA: ideal is NOT the two binomials: {out}")
    MAN.mark("SA_ideal")
    print("SA:", R["SA"], flush=True)


