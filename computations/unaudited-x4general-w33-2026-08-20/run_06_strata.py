def stratum_B():
    P = [0, 2, 4, 6]
    cells = []
    for i in range(N):
        u, v = i, (i + 1) % N
        a = i % 2
        cells.append(((min(u, v), max(u, v)), a, a))
    for (u, v) in itertools.combinations(P, 2):
        for a in range(2):
            for b in range(2):
                cells.append(((u, v), a, b))
    base = len(cells)
