def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def determinant(matrix):
    matrix = [[Q(value) for value in row] for row in matrix]
    size = len(matrix)
    require(all(len(row) == size for row in matrix), "matrix is not square")
    answer = Q(1)
    for column in range(size):
        pivot = next((row for row in range(column, size)
                      if matrix[row][column]), None)
        if pivot is None:
            return Q(0)
        if pivot != column:
            matrix[column], matrix[pivot] = matrix[pivot], matrix[column]
            answer = -answer
        value = matrix[column][column]
        answer *= value
        matrix[column] = [entry / value for entry in matrix[column]]
        for row in range(column + 1, size):
            factor = matrix[row][column]
            if factor:
                matrix[row] = [left - factor * right for left, right in
                               zip(matrix[row], matrix[column], strict=True)]
    return answer


def rank(matrix):
    matrix = [[Q(value) for value in row] for row in matrix]
    if not matrix:
        return 0
    height, width = len(matrix), len(matrix[0])
    require(all(len(row) == width for row in matrix), "ragged matrix")
    pivot_row = 0
    for column in range(width):
        pivot = next((row for row in range(pivot_row, height)
                      if matrix[row][column]), None)
        if pivot is None:
            continue
        matrix[pivot_row], matrix[pivot] = matrix[pivot], matrix[pivot_row]
        value = matrix[pivot_row][column]
        matrix[pivot_row] = [entry / value for entry in matrix[pivot_row]]
        for row in range(height):
            if row == pivot_row or not matrix[row][column]:
                continue
            factor = matrix[row][column]
            matrix[row] = [left - factor * right for left, right in
                           zip(matrix[row], matrix[pivot_row], strict=True)]
        pivot_row += 1
        if pivot_row == height:
            break
    return pivot_row


def minor(matrix, deleted_row, deleted_column):
    return [
        [value for column, value in enumerate(row)
         if column != deleted_column]
        for row_index, row in enumerate(matrix) if row_index != deleted_row
    ]


def adjugate(matrix):
    size = len(matrix)
    return [[
        Q((-1) ** (row + column))
        * determinant(minor(matrix, column, row))
        for column in range(size)
    ] for row in range(size)]


def dot(left, right):
    return sum((Q(a) * Q(b) for a, b in zip(left, right, strict=True)), Q(0))


def matvec(matrix, vector):
    return tuple(dot(row, vector) for row in matrix)


def transpose(matrix):
    return [list(column) for column in zip(*matrix, strict=True)]


def add(left, right):
    return tuple(Q(a) + Q(b) for a, b in zip(left, right, strict=True))


def scale(value, vector):
    return tuple(Q(value) * Q(entry) for entry in vector)


def compatible_cycle(size):
    """A weighted even cycle with prescribed full-support right charge."""
    require(size >= 4 and size % 2 == 0, "cycle must be even and nondegenerate")
    charge = tuple(Q((-1) ** index * (index + 1)) for index in range(size))
    matrix = [[Q(0) for _ in range(size)] for _ in range(size)]
    for row in range(size):
        u = Q(row + 2, row + 1)
        nxt = (row + 1) % size
        v = -u * charge[row] / charge[nxt]
        matrix[row][row] = u
        matrix[row][nxt] = v
    require(rank(matrix) == size - 1 and matvec(matrix, charge) == (Q(0),) * size,
            "compatible cycle lost its right charge")

    # For this cyclic block, the recurrence from M^T ell=0 determines a
    # full-support left charge.  Normalize ell_0=1.
    left = [Q(0)] * size
    left[0] = Q(1)
    for column in range(1, size):
        previous = column - 1
        left[column] = -left[previous] * matrix[previous][column] / matrix[column][column]
    require(matvec(transpose(matrix), left) == (Q(0),) * size
            and all(left), "compatible cycle lost its left charge")
    return matrix, charge, tuple(left)


def solve_image(matrix, target):
    """Return one exact solution Mx=target, or None."""
    height, width = len(matrix), len(matrix[0])
    work = [[Q(value) for value in row] + [Q(target[index])]
            for index, row in enumerate(matrix)]
    pivots = []
    pivot_row = 0
    for column in range(width):
        pivot = next((row for row in range(pivot_row, height)
                      if work[row][column]), None)
        if pivot is None:
            continue
        work[pivot_row], work[pivot] = work[pivot], work[pivot_row]
        value = work[pivot_row][column]
        work[pivot_row] = [entry / value for entry in work[pivot_row]]
        for row in range(height):
            if row == pivot_row or not work[row][column]:
                continue
            factor = work[row][column]
            work[row] = [left - factor * right for left, right in
                         zip(work[row], work[pivot_row], strict=True)]
        pivots.append(column)
        pivot_row += 1
    if any(not any(row[:width]) and row[-1] for row in work):
        return None
    answer = [Q(0)] * width
    for row, column in enumerate(pivots):
        answer[column] = work[row][-1]
    require(matvec(matrix, answer) == tuple(map(Q, target)), "bad image solution")
    return tuple(answer)


def audit_cycle(size):
    matrix, right, left = compatible_cycle(size)
    adj = adjugate(matrix)
    pivot = next((i, j) for i in range(size) for j in range(size)
                 if adj[i][j])
    i, j = pivot
    kappa = adj[i][j] / (right[i] * left[j])
    require(kappa and all(
        adj[row][column] == kappa * right[row] * left[column]
        for row in range(size) for column in range(size)
    ), "adjugate stopped being the kernel outer product")

    coordinate_records = []
    for selected in range(size):
        h = tuple(Q(int(index == selected)) for index in range(size))
        for connector in range(size):
            g = tuple(Q(int(index == connector)) for index in range(size))
            augmented = [row + [g[index]]
                         for index, row in enumerate(matrix)]
            augmented.append(list(h) + [Q(0)])
            actual = determinant(augmented)
            expected = -kappa * dot(h, right) * dot(left, g)
            require(actual == expected and actual,
                    "coordinate Cartan connector failed to kill even cycle")
            coordinate_records.append((selected, connector, str(actual)))

    # Every connector orthogonal to the left charge is component-exact.
    potential = tuple(Q(index + 1, size + 1) for index in range(size))
    exact_connector = matvec(matrix, potential)
    require(dot(left, exact_connector) == 0, "image connector left the kernel hyperplane")
    solved = solve_image(matrix, exact_connector)
    require(solved is not None, "left-orthogonal connector was not in im(M)")

    nonexact = add(exact_connector, tuple(Q(int(index == 0))
                                          for index in range(size)))
    require(dot(left, nonexact) != 0 and solve_image(matrix, nonexact) is None,
            "nonzero Cartan amplitude did not detect the image quotient")
    return {
        "size": size,
        "rank": rank(matrix),
        "right_charge": [str(value) for value in right],
        "left_charge": [str(value) for value in left],
        "adjugate_scale": str(kappa),
        "coordinate_anchor_connector_tests": len(coordinate_records),
        "every_coordinate_test_nonzero": True,
        "component_exact_test": {
            "left_pairing": str(dot(left, exact_connector)),
            "solution_exists": solved is not None,
        },
        "nonexact_test": {
            "left_pairing": str(dot(left, nonexact)),
            "solution_exists": False,
        },
    }


