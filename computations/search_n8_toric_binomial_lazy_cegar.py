"""Lazy exact search for arbitrary-complex binomial counterexamples at n=8.

The existing signed search restricts every selected aggregate cell to weight
``+1`` or ``-1``.  This search keeps the same sound support condition -- each
mixed fibre is empty or has exactly two perfect matchings, while every pure
fibre has one prescribed matching -- but tests the resulting Laurent system

    x**(a_M-a_N) = -1

over the full complex torus.  Consistency is decided by an integer HNF, not
by reducing the exponent equations modulo two.  If a support survives, a
Smith decomposition reconstructs rational phases and hence explicit roots
of unity.  A direct independent enumeration then checks all 3**8 fibres.

An inconsistent Laurent chart yields a sound support nogood: a future valid
0/2-fibre support cannot retain both terms of every contradictory binomial.
The learned clause therefore guards the union of their selected cells.
"""

