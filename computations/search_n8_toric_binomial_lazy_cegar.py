def image_guard(guard, vertex_permutation, colour_permutation):
    image = []
    for u, v, a, b in guard:
        image_u, image_v = vertex_permutation[u], vertex_permutation[v]
        image_a, image_b = colour_permutation[a], colour_permutation[b]
        if image_u > image_v:
            image_u, image_v = image_v, image_u
            image_a, image_b = image_b, image_a
        image.append((image_u, image_v, image_a, image_b))
    return frozenset(image)


@lru_cache(maxsize=1)
def global_diagonal_triangle_guards():
    """Return all 60,480 relabelings of the two checked guard schemas."""

    vertex_permutations = tuple(permutations(range(signed.N)))
    colour_permutations = tuple(permutations(range(signed.Q)))
    orbits = []
    for representative in DIAGONAL_TRIANGLE_GUARD_REPRESENTATIVES:
        orbit = {
            image_guard(representative, vertex, colour)
            for vertex in vertex_permutations
            for colour in colour_permutations
        }
        assert len(orbit) == 30240
        orbits.append(orbit)
    assert orbits[0].isdisjoint(orbits[1])
    guards = orbits[0] | orbits[1]
    assert len(guards) == 60480
    return tuple(sorted(guards, key=lambda guard: tuple(sorted(guard))))


