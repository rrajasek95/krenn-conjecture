@lru_cache(maxsize=None)
def target_one_row_pure_zero_schemas(targets):
    """Return every one-row pure-zero schema compatible with ``targets``.

    If the exact pure fibre has terms ``P,Q`` and contains its forced target
    ``P``, equality (up to sign) of a mixed exponent-difference row with the
    pure row forces the following form.  The two mixed matchings use precisely
    ``P-Q`` and ``Q-P`` on the alternating-cycle vertices, all colored by the
    pure color, and share an arbitrary perfect matching on the vertices of
    ``P & Q``.  Those shared vertices carry an arbitrary nonconstant color
    assignment.  Conversely every such choice gives the common-factor
    identity, so this enumeration is complete for one-row certificates in a
    fixed-target search.
    """

    pure_targets = tuple(frozenset(matching) for matching in targets)
    assert len(pure_targets) == signed.Q
    assert all(len(matching) == signed.N // 2 for matching in pure_targets)
    matchings = tuple(
        frozenset(matching)
        for matching in signed.core.perfect_matchings(tuple(range(signed.N)))
    )
    schemas = set()
    for colour, target in enumerate(pure_targets):
        for other in matchings:
            if other == target:
                continue
            common = target & other
            if not common:
                # With no shared pure edge every vertex occurs in the pure
                # exponent difference, so an equal mixed row is monochrome.
                continue
            assert len(common) in (1, 2)
            common_vertices = tuple(sorted({
                vertex for edge in common for vertex in edge
            }))
            target_only = target - common
            other_only = other - common
            for shared in signed.core.perfect_matchings(common_vertices):
                mixed_first = tuple(sorted(target_only | set(shared)))
                mixed_second = tuple(sorted(other_only | set(shared)))
                assert len(mixed_first) == len(mixed_second) == signed.N // 2
                for assigned in product(
                    range(signed.Q), repeat=len(common_vertices)
                ):
                    coloring = [colour] * signed.N
                    for vertex, value in zip(common_vertices, assigned):
                        coloring[vertex] = value
                    if all(value == colour for value in coloring):
                        continue
                    coloring = tuple(coloring)
                    guard = frozenset(
                        signed.decorated_term(coloring, mixed_first)
                        + signed.decorated_term(coloring, mixed_second)
                    )
                    schemas.add((
                        guard,
                        colour,
                        frozenset((target, other)),
                    ))

    assert len(schemas) == 9408
    assert Counter(len(guard) for guard, _colour, _terms in schemas) == {
        6: 8640,
        7: 768,
    }
    return tuple(sorted(
        schemas,
        key=lambda item: (
            tuple(sorted(item[0])),
            item[1],
            tuple(sorted(tuple(sorted(matching)) for matching in item[2])),
        ),
    ))


@lru_cache(maxsize=None)
def target_complete_one_row_pure_zero_schemas(targets):
    """Extend the target pair schemas to every one-row zero pure fibre.

    A six-cycle difference has only the target's single pure matching pair.
    A four-cycle difference has three disjoint pure matching pairs, one for
    each perfect matching on the four complementary vertices.  In the latter
    case the exact pure polynomial vanishes precisely when its term set is a
    nonempty union of complete pairs; because the forced target belongs to one
    distinguished pair, there are four allowed unions of sizes 2, 4, 4, 6.
    """

    pure_targets = tuple(frozenset(matching) for matching in targets)
    schemas = set()
    for guard, colour, pure_pair in target_one_row_pure_zero_schemas(targets):
        target = pure_targets[colour]
        assert target in pure_pair
        other, = pure_pair - {target}
        common = target & other
        if len(common) == 1:
            schemas.add((guard, colour, pure_pair))
            continue
        assert len(common) == 2
        common_vertices = tuple(sorted({
            vertex for edge in common for vertex in edge
        }))
        target_only = target - common
        other_only = other - common
        paired_terms = []
        for shared in signed.core.perfect_matchings(common_vertices):
            paired_terms.append(frozenset((
                frozenset(target_only | set(shared)),
                frozenset(other_only | set(shared)),
            )))
        assert len(paired_terms) == 3
        assert len(set(paired_terms)) == 3
        assert pure_pair in paired_terms
        optional = tuple(pair for pair in paired_terms if pair != pure_pair)
        assert len(optional) == 2
        for included in product((False, True), repeat=2):
            present = set(pure_pair)
            for use_pair, pair in zip(included, optional):
                if use_pair:
                    present.update(pair)
            schemas.add((guard, colour, frozenset(present)))

    assert len(schemas) == 35328
    assert Counter(len(terms) for _guard, _colour, terms in schemas) == {
        2: 9408,
        4: 17280,
        6: 8640,
    }
    assert Counter(len(guard) for guard, _colour, _terms in schemas) == {
        6: 34560,
        7: 768,
    }
    return tuple(sorted(
        schemas,
        key=lambda item: (
            tuple(sorted(item[0])),
            item[1],
            tuple(sorted(tuple(sorted(matching)) for matching in item[2])),
        ),
    ))


