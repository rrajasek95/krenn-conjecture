def numeric_layers(q, r):
    layers = [Q(0)] * 4
    for matching in matchings(SITES):
        for flags in product((0, 1), repeat=3):
            term = Q(1)
            for flag, e in zip(flags, matching):
                term *= (r if flag else q)[e]
            layers[sum(flags)] += term
    return tuple(layers)


def audit_clean_packet():
    q = {e: Q(0) for e in PAIRS}
    for e in ((0, 1), (2, 3), (4, 5)):
        q[e] = Q(1)
    u = (1, -1, 2, 0, 1, 1)
    v = (1, 2, -2, 1, -2, 1)
    r = {(x, y): Q(u[x] * v[y] + v[x] * u[y]) for x, y in PAIRS}
    layers = numeric_layers(q, r)
    require(layers == (Q(1), Q(2), Q(6), Q(12)), ("clean packet layers", layers))
    require(Q(-2) * layers[0] + layers[1] == 0, "clean packet source row moved")
    require(Q(-2) * layers[2] + layers[3] == 0, "the clean packet is not clean")


GUARD = ((0, 1, 2, 2, 1), (4, 5, 2, 2, 1), (LEFT, RIGHT, 0, 1, 1),
         (LEFT, 0, 0, 2, 1), (LEFT, 1, 0, 2, 1), (LEFT, 4, 1, 2, 1),
         (LEFT, 2, 2, 2, 1), (LEFT, 3, 2, 2, 1), (RIGHT, 5, 0, 2, 1),
         (RIGHT, 2, 1, 2, 1), (RIGHT, 3, 1, 2, -1),
         (RIGHT, 2, 2, 2, Q(1, 2)), (RIGHT, 3, 2, 2, Q(1, 2)))


def audit_seven_row_guard():
    blocks = {}
    for x, y, cx, cy, value in GUARD:
        if x > y:
            x, y, cx, cy = y, x, cy, cx
        blocks[(x, y, cx, cy)] = Q(value)

    def entry(x, y, cx, cy):
        if x > y:
            x, y, cx, cy = y, x, cy, cx
        return blocks.get((x, y, cx, cy), Q(0))

    def haf(word, sites):
        total = Q(0)
        for matching in matchings(tuple(sites)):
            term = Q(1)
            for x, y in matching:
                term *= entry(x, y, word[x], word[y])
                if not term:
                    break
            total += term
        return total

    ledger = []
    for word in product(COLORS, repeat=6):
        for i, j in product(COLORS, repeat=2):
            value = entry(LEFT, RIGHT, i, j) * haf(word, SITES)
            for x, y in PAIRS:
                piece = (entry(LEFT, x, i, word[x]) * entry(RIGHT, y, j, word[y])
                         + entry(LEFT, y, i, word[y])
                         * entry(RIGHT, x, j, word[x]))
                if piece:
                    value += piece * haf(word,
                                         tuple(v for v in SITES
                                               if v not in (x, y)))
            residual = value - ghz_target(i, j, word)
            if residual:
                ledger.append((i, j, word, residual))
    require(ledger == [(0, 0, (0,) * 6, Q(-1)), (1, 1, (1,) * 6, Q(-1))],
            ("the guard ledger changed", ledger))
    alpha = entry(LEFT, RIGHT, 0, 1)
    internal = {e: entry(e[0], e[1], PURE, PURE) for e in PAIRS}
    u = [entry(LEFT, x, 0, PURE) for x in SITES]
    v = [entry(RIGHT, x, 1, PURE) for x in SITES]
    r = {(x, y): u[x] * v[y] + v[x] * u[y] for x, y in PAIRS}
    layers = numeric_layers(internal, r)
    require(alpha * layers[2] + layers[3] == -2, "the guard chi changed")
    return len(ledger)


