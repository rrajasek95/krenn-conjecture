from fractions import Fraction as Q
from itertools import combinations, permutations, product


def require(condition, message):
    if not condition:
        raise AssertionError(message)


COLORS = (0, 1, 2)
SITES = tuple(range(6))
PAIRS = tuple(combinations(SITES, 2))
LEFT, RIGHT = 6, 7
PURE = 2
SEVEN = ((0, 1), (0, 2), (1, 0), (1, 2), (2, 0), (2, 1), (2, 2))

_MATCH = {}


def matchings(vertices):
    vertices = tuple(vertices)
    if vertices in _MATCH:
        return _MATCH[vertices]
    if not vertices:
        answer = ((),)
    elif len(vertices) % 2:
        answer = ()
    else:
        first = vertices[0]
        acc = []
        for position, partner in enumerate(vertices[1:], start=1):
            remainder = vertices[1:position] + vertices[position + 1:]
            for tail in matchings(remainder):
                acc.append(((first, partner),) + tail)
        answer = tuple(acc)
    _MATCH[vertices] = answer
    return answer


# --------------------------------------------------------------------------
# exact sparse polynomials; a monomial is a sorted tuple of variable keys
# --------------------------------------------------------------------------
ONE = {(): Q(1)}


def var(key):
    return {(key,): Q(1)}


def padd(left, right):
    out = dict(left)
    for monomial, coefficient in right.items():
        total = out.get(monomial, Q(0)) + coefficient
        if total:
            out[monomial] = total
        elif monomial in out:
            del out[monomial]
    return out


def pmul(left, right):
    out = {}
    for m1, c1 in left.items():
        for m2, c2 in right.items():
            monomial = tuple(sorted(m1 + m2))
            total = out.get(monomial, Q(0)) + c1 * c2
            if total:
                out[monomial] = total
            elif monomial in out:
                del out[monomial]
    return out


def pscale(poly, factor):
    if not factor:
        return {}
    return {monomial: coefficient * factor for monomial, coefficient in poly.items()}


