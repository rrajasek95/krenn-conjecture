        available = [(i, j, word) for word in product(COLORS, repeat=6)
                     for i, j in product(COLORS, repeat=2)
                     if dominates(level, degree_of_generator(i, j, word))]
        require(available == [(colour, colour, anchor_word)],
                ("the constant's level-two system gained a generator", colour,
                 available))


