def q_key(x, y, cx, cy):
    if x > y:
        x, y = y, x
        cx, cy = cy, cx
    return ("q", x, y, cx, cy)


CROSS = [True]                         # cross-colour internal edges present?


def q_var(x, y, cx, cy):
    if cx != cy and not CROSS[0]:
        return {}                      # the monochromatic specialization
    return var(q_key(x, y, cx, cy))


def set_cross(flag):
    """Killing the cross-colour internal edges is a graded ring homomorphism
    that fixes chi and every label; a depth-one certificate maps to a
    depth-one certificate, so deciding the monochromatic model decides the
    general one in the negative direction."""
    CROSS[0] = flag
    _HAF.clear()
    _ROW.clear()


def p_var(i, x, c):
    return var(("p", i, x, c))


def s_var(j, y, c):
    return var(("s", j, y, c))


def d_var(i, j):
    return var(("d", i, j))


_HAF = {}


def haf_poly(sites, word):
    sites = tuple(sites)
    key = (sites, tuple(word[x] for x in sites))
    cached = _HAF.get(key)
    if cached is not None:
        return cached
    total = {}
    for matching in matchings(sites):
        term = ONE
        for x, y in matching:
            term = pmul(term, q_var(x, y, word[x], word[y]))
            if not term:
                break
        total = padd(total, term)
    _HAF[key] = total
    return total


def response(i, j, x, y, word):
    return padd(pmul(p_var(i, x, word[x]), s_var(j, y, word[y])),
                pmul(p_var(i, y, word[y]), s_var(j, x, word[x])))


_ROW = {}


def row_poly(i, j, word):
    key = (i, j, word)
    cached = _ROW.get(key)
    if cached is not None:
        return cached
    total = pmul(d_var(i, j), haf_poly(SITES, word))
    for x, y in PAIRS:
        piece = haf_poly(tuple(v for v in SITES if v not in (x, y)), word)
        if piece:
            total = padd(total, pmul(response(i, j, x, y, word), piece))
    _ROW[key] = total
    return total


def ghz_target(i, j, word):
    return Q(1) if (i == j and all(c == i for c in word)) else Q(0)


def chi_poly(a=0, b=1, colour=PURE):
    word = (colour,) * 6
    layers = [{} for _ in range(4)]
    for matching in matchings(SITES):
        for flags in product((0, 1), repeat=3):
            term = ONE
            for flag, (x, y) in zip(flags, matching):
                term = pmul(term, response(a, b, x, y, word) if flag
                            else q_var(x, y, colour, colour))
            layers[sum(flags)] = padd(layers[sum(flags)], term)
    return padd(pmul(d_var(a, b), layers[2]), layers[3]), layers


