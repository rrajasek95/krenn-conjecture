FROZEN_Q2 = {(0, 1): Q(1), (4, 5): Q(1)}
FROZEN_P2 = {(0, 0): Q(1), (0, 1): Q(1), (1, 4): Q(1), (2, 2): Q(1), (2, 3): Q(1)}
FROZEN_S2 = {(0, 5): Q(1), (1, 2): Q(1), (1, 3): Q(-1),
             (2, 2): Q(1, 2), (2, 3): Q(1, 2)}


def frozen_edge(x, y, cx, cy):
    if x > y:
        x, y, cx, cy = y, x, cy, cx
    if cx == PURE and cy == PURE:
        value = FROZEN_Q2.get((x, y), 0)
        return {(): Q(value)} if value else {}
    if cx != cy:
        return {}
    return var(("q", cx, min(x, y), max(x, y)))


def frozen_p(i, x, c):
    if c == PURE:
        value = FROZEN_P2.get((i, x), 0)
        return {(): Q(value)} if value else {}
    return var(("p", i, x, c))


def frozen_s(j, y, c):
    if c == PURE:
        value = FROZEN_S2.get((j, y), 0)
        return {(): Q(value)} if value else {}
    return var(("s", j, y, c))


def frozen_haf(vertices, word):
    total = {}
    for matching in matchings(tuple(vertices)):
        term = ONE
        for x, y in matching:
            term = pmul(term, frozen_edge(x, y, word[x], word[y]))
            if not term:
                break
        total = padd(total, term)
    return total


def frozen_row(i, j, word, vertices=SITES):
    vertices = tuple(vertices)
    total = pmul(var(("d", i, j)), frozen_haf(vertices, word))
    for x, y in combinations(vertices, 2):
        piece = frozen_haf(tuple(v for v in vertices if v not in (x, y)), word)
        if not piece:
            continue
        resp = padd(pmul(frozen_p(i, x, word[x]), frozen_s(j, y, word[y])),
                    pmul(frozen_p(i, y, word[y]), frozen_s(j, x, word[x])))
        if resp:
            total = padd(total, pmul(resp, piece))
    return total


def kill(poly, zeros):
    return {m: v for m, v in poly.items() if not any(k in zeros for k in m)}


def audit_template():
    system = {(i, j, w): frozen_row(i, j, w)
              for w in product(COLORS, repeat=6)
              for i, j in product(COLORS, repeat=2)}
    ledger = []
    for (i, j, word), poly in system.items():
        value = Q(0)
        for monomial, coefficient in poly.items():
            term = coefficient
            for key in monomial:
                term *= Q(1) if key == ("d", 0, 1) else Q(0)
            value += term
        residual = value - ghz_target(i, j, word)
        if residual:
            ledger.append((i, j, word, residual))
    require(sorted(ledger) == [(0, 0, (0,) * 6, Q(-1)), (1, 1, (1,) * 6, Q(-1))],
            ("the frozen model misses the committed guard ledger",
             sorted(ledger)))

    equations = [(k, padd(p, {(): -ghz_target(*k)}))
                 for k, p in system.items() if (k[0], k[1]) in SEVEN]
    zeros = set()
    while True:
        fresh = set()
        for key, poly in equations:
            reduced = kill(poly, zeros)
            if len(reduced) != 1:
                continue
            monomial = next(iter(reduced))
            require(monomial, ("premature contradiction", key))
            if len(set(monomial)) == 1:
                require(len(monomial) == 1, ("a forcing is not linear", key))
                fresh.add(monomial[0])
        if not fresh - zeros:
            break
        zeros |= fresh
    require(len(zeros) == 32, ("forced zero count", len(zeros)))
    for colour in (0, 1):
        alive = tuple(pair for pair in PAIRS
                      if ("q", colour, pair[0], pair[1]) not in zeros)
        require(alive == ((0, 4), (0, 5), (1, 4), (1, 5), (2, 3)),
                ("colour-%d support collapse changed" % colour, alive))
        anchor = kill(system[(colour, colour, (colour,) * 6)], zeros)
        rho = kill(frozen_row(colour, colour, {x: colour for x in SITES},
                              vertices=(0, 1, 4, 5)), zeros)
        require(anchor == pmul(var(("q", colour, 2, 3)), rho),
                ("the anchor peel identity failed", colour))

    residuals = {}
    for colour in (0, 1):
        anchor = kill(system[(colour, colour, (colour,) * 6)], zeros)
        words = {"E3": tuple(PURE if x in (2, 3) else colour for x in SITES),
                 "E4": tuple(PURE if x == 0 else colour for x in SITES),
                 "E5": tuple(PURE if x == 1 else colour for x in SITES),
                 "E6": tuple(PURE if x in (1, 4, 5) else colour for x in SITES),
                 "E7": tuple(PURE if x in (0, 4, 5) else colour for x in SITES)}
        labels = {"E3": (2, 2), "E4": (0, 1), "E5": (0, 1),
                  "E6": (0, 1), "E7": (0, 1)}
        piece = {}
        for name, word in words.items():
            i, j = labels[name]
            require((i, j) in SEVEN, ("certificate used a non-supplied row", name))
            require(ghz_target(i, j, word) == 0,
                    ("certificate word has a target", name))
            piece[name] = kill(system[(i, j, word)], zeros)
        require(piece["E3"] == padd(pmul(var(("q", colour, 0, 4)),
                                         var(("q", colour, 1, 5))),
                                    pmul(var(("q", colour, 0, 5)),
                                         var(("q", colour, 1, 4)))),
                ("E3 is not the four-site permanent", colour))
        a_prime = padd(pmul(var(("q", colour, 1, 5)), var(("p", colour, 4, colour))),
                       pmul(var(("q", colour, 1, 4)), var(("p", colour, 5, colour))))
        c_prime = padd(pmul(var(("q", colour, 0, 5)), var(("p", colour, 4, colour))),
                       pmul(var(("q", colour, 0, 4)), var(("p", colour, 5, colour))))
        combination = pmul(pmul(var(("d", colour, colour)),
                                var(("q", colour, 2, 3))), piece["E3"])
        combination = padd(combination, pmul(var(("p", colour, 0, colour)),
                                             piece["E4"]))
        combination = padd(combination, pmul(var(("p", colour, 1, colour)),
                                             piece["E5"]))
        combination = padd(combination, pmul(a_prime, piece["E6"]))
        combination = padd(combination, pmul(c_prime, piece["E7"]))
        residuals[colour] = len(padd(anchor, pscale(combination, Q(-1))))
    require(residuals[1] == 0, ("the colour-1 certificate failed", residuals[1]))
    require(residuals[0] == 16,
            ("the colour-0 residual is not sixteen monomials", residuals[0]))
    return len(zeros)


