WEIGHT = {"q": -1, "p": 1, "s": 1, "d": 3}


def weight_of(monomial):
    return sum(WEIGHT[key[0]] for key in monomial)


def shape_of(monomial):
    counts = {"p": 0, "s": 0, "d": 0, "q": 0}
    for key in monomial:
        counts[key[0]] += 1
    return (counts["p"], counts["s"], counts["d"], counts["q"])


def degree_of(monomial):
    site = {}
    left = {}
    right = {}
    for key in monomial:
        if key[0] == "q":
            _, x, y, cx, cy = key
            site[(x, cx)] = site.get((x, cx), 0) + 1
            site[(y, cy)] = site.get((y, cy), 0) + 1
        elif key[0] == "p":
            _, i, x, c = key
            site[(x, c)] = site.get((x, c), 0) + 1
            left[i] = left.get(i, 0) + 1
        elif key[0] == "s":
            _, j, y, c = key
            site[(y, c)] = site.get((y, c), 0) + 1
            right[j] = right.get(j, 0) + 1
        else:
            left[key[1]] = left.get(key[1], 0) + 1
            right[key[2]] = right.get(key[2], 0) + 1
    return (frozenset(site.items()), frozenset(left.items()),
            frozenset(right.items()))


def as_dict(degree):
    return tuple(dict(part) for part in degree)


def dominates(big, small):
    for part_big, part_small in zip(as_dict(big), as_dict(small)):
        for key, value in part_small.items():
            if part_big.get(key, 0) < value:
                return False
    return True


def degree_of_generator(i, j, word):
    site = frozenset(((x, word[x]), 1) for x in SITES)
    return (site, frozenset({(i, 1)}), frozenset({(j, 1)}))


def homogeneous_degree(poly, name):
    degrees = {degree_of(m) for m in poly}
    require(len(degrees) == 1, ("not multihomogeneous", name, len(degrees)))
    return degrees.pop()


