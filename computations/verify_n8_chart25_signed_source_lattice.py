EXPECTED_DIGEST = "0ce609a7aaf564f5387d3d4dfb07121a06925a3383bf3b62087cea71aca44165"


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def load(name, filename):
    spec = importlib.util.spec_from_file_location(name, HERE / filename)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


LITERAL = load(
    "chart25_signed_lattice_literal",
    "verify_n8_literal_hafnian_hpl_no_go.py",
)
RELATIVE = load(
    "chart25_signed_lattice_relative",
    "verify_n8_chart25_relative_4d_obstruction.py",
)
DUAL = LITERAL.DUAL
