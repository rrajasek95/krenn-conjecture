"""Exact signed-lattice classification of the chart-25 physical source graph.

The complete frozen partial-character support has 20 physical rows and 56
individually labelled mixed-source columns.  Its graph is four disjoint
four-leaf multistars.  This checker proves the integral split exact sequence

    0 -> Z^16 -> Z^20 -> Z^4 -> 0,

so the source image is saturated and its four primitive component
characters are the entire cokernel.  The 40 column syzygies are generated by
parallel-edge differences (doubled even cycles); the graph is bipartite and
has no odd handcuff.  Hence cycle/handcuff combinations and ordinary
label-diagonal Koszul closure cannot supply the missing chart-25 4D class.
"""

