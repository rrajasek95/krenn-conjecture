#!/usr/bin/env python3
"""Exact multi-spoke exposure on the selected chart-26 terminal face.

There are three separate assertions in this checker.

1.  At the chart-support boundary, the linear parts of 358 mixed hafnians
    contain an exact 240 by 240 identity minor.  Thus the 240 off-support
    coordinates are generated by the mixed ideal in the local ring at that
    boundary (Nakayama).
2.  On the selected Hamilton-row face, retain the 96 non-support coordinates
    on off-path edges incident to endpoint 2 or 5.  Raw support-unit
    triangular division exposes 80 of them.  The remaining sixteen lie on
    edges 24 and 56.  Each is exposed by a two-row Bezout identity, so all 96
    coordinates, and hence every clean-cap error on this restricted face,
    lie in the support-localized mixed ideal.
3.  Six path-edge decorations are the next clean-error directions outside
    that face.  They have Bezout identities after quotienting by the 96
    off-path coordinates, but adjoining them simultaneously creates genuine
    quadratic alternate-matching cycles.  No full-face conclusion is made.

All coordinates and all mixed words are retained with their literal source
labels.  Support normalization means localization at the twelve chart-26
support coordinates followed by setting those units to one.
"""

