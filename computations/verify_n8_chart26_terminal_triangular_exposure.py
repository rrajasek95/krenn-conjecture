def require(condition, detail):
    if not condition:
        raise RuntimeError(detail)


def word_text(word):
    return "".join(map(str, word))


def coordinate_text(variable_id):
    left, right, left_colour, right_colour = D5.COORDINATES[variable_id]
    return f"x{left}{right}_{left_colour}{right_colour}"


def normalized_hafnian(word, active_variables):
    """Restrict H_word, invert support, and return a sparse polynomial."""
    active = SUPPORT | frozenset(active_variables)
    answer = Counter()
    for term in D5.iter_word_terms(D5.word_code(word)):
        if set(term).issubset(active):
            answer[bytes(
                variable_id for variable_id in term
                if variable_id not in SUPPORT
            )] += 1
    return dict(answer)


def mixed_words():
    for word in product(range(3), repeat=8):
        if len(set(word)) != 1:
            yield word


def polynomial_without_ideal(polynomial, ideal_variables):
    ideal = frozenset(ideal_variables)
    return {
        monomial: coefficient
        for monomial, coefficient in polynomial.items()
        if not set(monomial).intersection(ideal)
    }


def support_boundary_audit():
    off_support = frozenset(range(len(D5.COORDINATES))) - SUPPORT
    linear_rows = {}
    options = defaultdict(list)
    full_polynomials = {}

    for word in mixed_words():
        polynomial = normalized_hafnian(word, off_support)
        linear = {
            monomial[0]: coefficient
            for monomial, coefficient in polynomial.items()
            if len(monomial) == 1
        }
        if not linear:
            continue
        require(b"" not in polynomial,
                "a support-boundary exposure row acquired a constant")
        require(len(linear) == 1 and set(linear.values()) == {1},
                "a support-boundary linear row stopped being one-hot")
        variable_id = next(iter(linear))
        linear_rows[word] = variable_id
        options[variable_id].append(word)
        full_polynomials[word] = polynomial

    require(len(off_support) == 240,
            "off-support coordinate census changed")
    require(len(linear_rows) == 358,
            "support-boundary mixed linear-row census changed")
    require(set(options) == off_support,
            "the support-boundary linearization lost a coordinate")
    option_histogram = Counter(map(len, options.values()))
    require(option_histogram == Counter({1: 130, 2: 102, 3: 8}),
            "support-boundary exposure-option histogram changed")

    # Every nonzero row has exactly one entry 1, so choosing one row for each
    # coordinate literally gives an identity matrix over Z, not merely full
    # rank modulo a prime.  The remaining terms have off-support degree >= 2.
    pivots = {}
    for variable_id in sorted(off_support):
        word = min(options[variable_id])
        polynomial = full_polynomials[word]
        require(polynomial.get(bytes((variable_id,))) == 1,
                "selected support-boundary pivot changed")
        require(all(
            monomial == bytes((variable_id,)) or len(monomial) >= 2
            for monomial in polynomial
        ), "a support-boundary pivot gained another linear term")
        pivots[variable_id] = word

    pivot_digest = sha256()
    for variable_id, word in sorted(pivots.items()):
        pivot_digest.update(bytes((variable_id,)))
        pivot_digest.update(bytes(word))

    return {
        "off_support_coordinates": len(off_support),
        "nonzero_mixed_linear_rows": len(linear_rows),
        "row_support_histogram": {1: len(linear_rows)},
        "coordinate_option_histogram": dict(sorted(option_histogram.items())),
        "selected_identity_minor_size": len(pivots),
        "selected_identity_minor_determinant": 1,
        "selected_pivot_digest": pivot_digest.hexdigest(),
        "nakayama_conclusion": (
            "in the support-boundary local ring, m=I_mix+m^2 and hence "
            "m=I_mix for the ideal m of all 240 off-support coordinates"
        ),
    }


