#!/usr/bin/env python3
"""Clean-room exact audit of the scalar common-origin countermodel.

This deliberately does not import the primary verifier.  Square-free
monomials are six-bit masks, divided powers are generated by choosing
compatible edge-index subsets, and the symbolic cofactor block is read in
the reversed bipartition order (4,5,0 | 3,2,1).
"""

from __future__ import annotations

from fractions import Fraction
from itertools import combinations, permutations

import sympy as sp


N = 6
FULL = (1 << N) - 1


def mask(*vertices: int) -> int:
    value = 0
    for vertex in vertices:
        value |= 1 << vertex
    return value


def clean(poly: dict[int, object]) -> dict[int, object]:
    return {monomial: coefficient for monomial, coefficient in poly.items() if coefficient != 0}


def product(left: dict[int, object], right: dict[int, object]) -> dict[int, object]:
    """Product in tensor_u F[z_u]/(z_u^2), using bit masks."""
    answer: dict[int, object] = {}
    for monomial_left, coefficient_left in left.items():
        for monomial_right, coefficient_right in right.items():
            if monomial_left & monomial_right:
                continue
            monomial = monomial_left | monomial_right
            answer[monomial] = answer.get(monomial, 0) + coefficient_left * coefficient_right
    return clean(answer)


def scaled(poly: dict[int, object], scalar: object) -> dict[int, object]:
    return clean({monomial: scalar * coefficient for monomial, coefficient in poly.items()})


def divided_selection(
    edge_terms: tuple[tuple[int, object], ...], degree: int
) -> dict[int, object]:
    """Choose unordered sets of ``degree`` pairwise-disjoint edge terms."""
    answer: dict[int, object] = {}
    for chosen_indices in combinations(range(len(edge_terms)), degree):
        occupied = 0
        coefficient: object = 1
        compatible = True
        for index in chosen_indices:
            edge, weight = edge_terms[index]
            if occupied & edge:
                compatible = False
                break
            occupied |= edge
            coefficient *= weight
        if compatible:
            answer[occupied] = answer.get(occupied, 0) + coefficient
    return clean(answer)


def cofactor_matrix(divided_square: dict[int, object]) -> sp.Matrix:
    return sp.Matrix(
        N,
        N,
        lambda row, column: (
            0
            if row == column
            else divided_square.get(FULL ^ mask(row, column), 0)
        ),
    )


def symbolic_audit() -> None:
    a, b, c, d, e, f = sp.symbols("a b c d e f")

    # Reverse-order listing of the cycle 0-1-5-2-4-3-0.
    edges = (
        (mask(3, 4), e),
        (mask(2, 4), d),
        (mask(2, 5), c),
        (mask(1, 5), b),
        (mask(0, 1), a),
        (mask(0, 3), f),
    )
    compatible_triples = []
    for chosen in combinations(edges, 3):
        if chosen[0][0] & chosen[1][0] or chosen[0][0] & chosen[2][0] or chosen[1][0] & chosen[2][0]:
            continue
        compatible_triples.append(sp.prod(term[1] for term in chosen))
    assert compatible_triples == [a * c * e, b * d * f]

    q2 = divided_selection(edges, 2)
    q3 = divided_selection(edges, 3)
    assert sp.expand(q3[FULL]) == a * c * e + b * d * f

    C = cofactor_matrix(q2)
    left = (4, 5, 0)
    right = (3, 2, 1)
    E = C.extract(left, right)
    expected_E = sp.Matrix(
        (
            (a * c, b * f, c * f),
            (a * d, a * e, d * f),
            (b * d, b * e, c * e),
        )
    )
    assert E == expected_E
    assert C.extract(left, left) == sp.zeros(3)
    assert C.extract(right, right) == sp.zeros(3)
    assert C.extract(right, left) == E.T
    assert sp.factor(E.det()) == (a * c * e - b * d * f) ** 2
    assert sp.factor(C.det()) == -(a * c * e - b * d * f) ** 4

    # Check the restriction to ace+bdf=0 without dividing by a parameter.
    relation_remainder = sp.rem(
        sp.Poly(C.det() + 16 * (a * c * e) ** 4, f),
        sp.Poly(a * c * e + b * d * f, f),
    )
    assert relation_remainder.as_expr() == 0


def rational_audit() -> None:
    # Again use the reverse cycle listing, independent of the primary code's
    # dictionary insertion order.
    edges = (
        (mask(3, 4), Fraction(1)),
        (mask(2, 4), Fraction(1)),
        (mask(2, 5), Fraction(-1)),
        (mask(1, 5), Fraction(1)),
        (mask(0, 1), Fraction(2)),
        (mask(0, 3), Fraction(2)),
    )
    q = {edge: weight for edge, weight in edges}
    F = divided_selection(edges, 2)
    q3 = divided_selection(edges, 3)

    expected_F = {
        mask(0, 1, 2, 4): Fraction(2),
        mask(0, 1, 2, 5): Fraction(-2),
        mask(0, 1, 3, 4): Fraction(2),
        mask(0, 1, 3, 5): Fraction(2),
        mask(0, 2, 3, 4): Fraction(2),
        mask(0, 2, 3, 5): Fraction(-2),
        mask(1, 2, 4, 5): Fraction(1),
        mask(1, 3, 4, 5): Fraction(1),
        mask(2, 3, 4, 5): Fraction(-1),
    }
    assert F == expected_F
    assert q3 == {}
    assert product(q, q) == scaled(F, 2)
    assert product(q, F) == {}

    C = cofactor_matrix(F)
    expected_C = sp.Matrix(
        (
            (0, -1, 1, 1, 0, 0),
            (-1, 0, 0, 0, -2, 2),
            (1, 0, 0, 0, 2, 2),
            (1, 0, 0, 0, -2, 2),
            (0, -2, 2, -2, 0, 0),
            (0, 2, 2, 2, 0, 0),
        )
    )
    assert C == expected_C
    assert C.det() == -256

    p = (
        {mask(0): Fraction(1)},
        {mask(1): Fraction(1)},
        {mask(2): Fraction(1)},
    )
    s = (
        {mask(1): Fraction(-1, 2), mask(3): Fraction(1, 2)},
        {mask(0): Fraction(-1, 2), mask(5): Fraction(1, 4)},
        {mask(4): Fraction(1, 4), mask(5): Fraction(1, 4)},
    )

    expected_A = (
        {
            mask(0, 1, 5): Fraction(1),
            mask(0, 2, 4): Fraction(1),
            mask(0, 2, 5): Fraction(-1),
            mask(0, 3, 4): Fraction(1),
        },
        {
            mask(0, 1, 3): Fraction(2),
            mask(1, 2, 4): Fraction(1),
            mask(1, 2, 5): Fraction(-1),
            mask(1, 3, 4): Fraction(1),
        },
        {
            mask(0, 1, 2): Fraction(2),
            mask(0, 2, 3): Fraction(2),
            mask(1, 2, 5): Fraction(1),
            mask(2, 3, 4): Fraction(1),
        },
    )
    expected_B = (
        {
            mask(1, 2, 4): Fraction(-1, 2),
            mask(1, 2, 5): Fraction(1, 2),
            mask(1, 3, 4): Fraction(-1, 2),
            mask(1, 3, 5): Fraction(1, 2),
            mask(2, 3, 4): Fraction(1, 2),
            mask(2, 3, 5): Fraction(-1, 2),
        },
        {
            mask(0, 2, 4): Fraction(-1, 2),
            mask(0, 2, 5): Fraction(1, 2),
            mask(0, 3, 4): Fraction(-1, 2),
            mask(0, 3, 5): Fraction(1, 2),
            mask(2, 4, 5): Fraction(1, 4),
            mask(3, 4, 5): Fraction(1, 4),
        },
        {
            mask(0, 1, 4): Fraction(1, 2),
            mask(0, 1, 5): Fraction(1, 2),
            mask(0, 3, 4): Fraction(1, 2),
            mask(0, 3, 5): Fraction(1, 2),
            mask(1, 4, 5): Fraction(1, 4),
            mask(3, 4, 5): Fraction(1, 4),
        },
    )
    A = tuple(product(row, q) for row in p)
    B = tuple(product(row, q) for row in s)
    assert A == expected_A
    assert B == expected_B

    response_table = []
    factor_table = []
    for i in range(3):
        response_row = []
        factor_row = []
        for j in range(3):
            response = product(product(p[i], s[j]), F)
            factored = product(A[i], B[j])
            expected_response = {FULL: Fraction(1)} if i == j else {}
            expected_factored = {FULL: Fraction(2)} if i == j else {}
            assert response == expected_response
            assert factored == expected_factored
            assert factored == scaled(response, 2)
            # Also compare with p_i s_j q^2, not merely its top coefficient.
            assert factored == product(product(p[i], s[j]), product(q, q))
            response_row.append(response.get(FULL, 0))
            factor_row.append(factored.get(FULL, 0))
        response_table.append(response_row)
        factor_table.append(factor_row)
    assert sp.Matrix(response_table) == sp.eye(3)
    assert sp.Matrix(factor_table) == 2 * sp.eye(3)

    # An independent check of the dual-row calculation, with columns read
    # in the nonstandard order 5,3,1,4,2,0 before returning to site order.
    strange_order = (5, 3, 1, 4, 2, 0)
    C_strange = C.extract(strange_order, strange_order)
    P_strange = sp.Matrix(
        [[1 if strange_order[column] == i else 0 for column in range(6)] for i in range(3)]
    )
    S_strange = sp.Matrix(
        [
            [row.get(mask(strange_order[column]), 0) for column in range(6)]
            for row in s
        ]
    )
    assert P_strange * C_strange * S_strange.T == sp.eye(3)


def independent_target_audit() -> None:
    """Exhaust the support claim in the note's separate three-colour example."""
    triples = tuple(mask(*vertices) for vertices in combinations(range(N), 3))
    assert len(triples) == 20
    checked = 0
    for chosen in permutations(triples, 3):
        if len(set(chosen)) != 3:
            continue
        for i in range(3):
            for j in range(3):
                left = chosen[i]
                right = FULL ^ chosen[j]
                if i == j:
                    assert left & right == 0
                    assert left | right == FULL
                else:
                    # Equal-size distinct sets cannot contain one another.
                    assert left & right != 0
        checked += 1
    assert checked == 20 * 19 * 18


def main() -> None:
    symbolic_audit()
    rational_audit()
    independent_target_audit()
    print("clean-room symbolic six-cycle determinant identity: PASS")
    print("explicit q^[2], q^[3], A_i, B_j, and all 18 response products: PASS")
    print("all 6,840 ordered distinct-triple target supports: PASS")
    print("scope check: scalar top-degree target is one-dimensional, not Krenn")


if __name__ == "__main__":
    main()
