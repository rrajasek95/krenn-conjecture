def fibre_relations(fibres, words, cells, cell_index):
    """Binomial exponent rows d = 1_{M_a} - 1_{M_b} for two-term fibres."""
    rows = []
    provenance = []
    for word in words:
        terms = fibres.get(word, [])
        if len(terms) != 2:
            continue
        (m_a, _, _), (m_b, _, _) = sorted(terms, key=lambda item: not item[2])
        row = [0] * len(cells)
        for edge in m_a:
            row[cell_index[cell_of_edge(edge)]] += 1
        for edge in m_b:
            row[cell_index[cell_of_edge(edge)]] -= 1
        rows.append(row)
        provenance.append(word)
    return rows, provenance


def classify(name, fibres, mixed_words, pure_words, cells, cell_index):
    """Apply O1/O2 to one subsystem and report the label."""
    print(f"\n  --- subsystem: {name} ---")
    print(f"      mixed target-zero equations : {len(mixed_words)}")
    print(f"      pure nonzero equations      : {len(pure_words)}")

    sizes: dict[int, int] = {}
    singletons = []
    for word in mixed_words:
        size = len(fibres.get(word, []))
        sizes[size] = sizes.get(size, 0) + 1
        if size == 1:
            singletons.append(word)
    print(f"      mixed fibre size census     : "
          f"{ {k: sizes[k] for k in sorted(sizes)} }")

    for word in pure_words:
        assert fibres.get(word), f"pure fibre {word} is empty"

    o2 = bool(singletons)
    if o2:
        sample = "".join(map(str, singletons[0]))
        print(f"      O2 (singleton class)        : FIRES on {len(singletons)} "
              f"one-term mixed fibres, e.g. {sample}")
    else:
        print("      O2 (singleton class)        : does not fire "
              "(no one-term mixed fibre)")

    rows, provenance = fibre_relations(fibres, mixed_words, cells, cell_index)
    print(f"      binomial exponent rows      : {len(rows)} "
          f"({', '.join(''.join(map(str, w)) for w in provenance)})")
    rank = rational_rank([[Fraction(v) for v in row] for row in rows]) if rows else 0
    print(f"      rank of the exponent rows   : {rank}"
          f"  (relation lattice rank {len(rows) - rank})")
    relation = odd_relation(rows)
    if relation is None:
        o1 = False
        print("      O1 (odd holonomy 1 = -1)    : DOES NOT FIRE -- every "
              "integer dependency among the binomial rows has even coefficient "
              "sum")
    else:
        o1 = True
        support = {provenance[k]: relation[k]
                   for k in range(len(rows)) if relation[k]}
        print(f"      O1 (odd holonomy 1 = -1)    : FIRES with coefficients "
              f"{ {''.join(map(str, w)): c for w, c in support.items()} }")
    return {"O1": o1, "O2": o2, "singletons": len(singletons),
            "rows": len(rows), "relation_rank": len(rows) - rank}


