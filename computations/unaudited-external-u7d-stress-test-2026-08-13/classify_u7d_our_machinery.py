Cell = tuple[int, int, int, int]          # (u, v, label at u, label at v)
Node = tuple[int, int]                    # (vertex, colour)


def support_cells() -> list[Cell]:
    """Their support as cells of our general bicoloured model."""
    return sorted((u, v, i, j) for (u, v), (i, j, _) in TABLE.items())


def cell_of_edge(edge) -> Cell:
    """The unique live cell on a physical pair (r = 1)."""
    left_label, right_label, _ = TABLE[edge]
    return (edge[0], edge[1], left_label, right_label)


def incidence_row(cell: Cell) -> dict[Node, int]:
    """Unsigned incidence image of a cell in Z^{V x 3}."""
    u, v, i, j = cell
    row: dict[Node, int] = {}
    row[(u, i)] = row.get((u, i), 0) + 1
    row[(v, j)] = row.get((v, j), 0) + 1
    return row


