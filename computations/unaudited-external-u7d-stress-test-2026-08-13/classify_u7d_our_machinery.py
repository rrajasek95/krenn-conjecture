def analyse_lattice():
    """Compare our L to their diagonal-gauge invariants on their support."""
    print("\nC. INVARIANT LATTICE AND GAUGE RECONCILIATION")
    cells = support_cells()
    nodes = [(vertex, colour) for vertex in range(ORDER)
             for colour in range(COLOURS)]
    node_index = {node: position for position, node in enumerate(nodes)}

    full_rows = []
    for cell in cells:
        row = [Fraction(0)] * len(nodes)
        for node, value in incidence_row(cell).items():
            row[node_index[node]] += value
        full_rows.append(row)
    rank_full = rational_rank([list(row) for row in full_rows])
    print(f"  support cells |S|                      : {len(cells)}")
    print(f"  rank of unsigned incidence on S        : {rank_full}")
    print(f"  rank L_S = ker(Z^S -> Z^(V x 3))       : {len(cells) - rank_full}")

    # the GHZ subtorus they use: prod_v b_{v,c} = 1 for every colour.
    # Its invariants are ker(Z^S -> Z^(V x 3) / <u_0, u_1, u_2>).
    ghz_rows = []
    for row in full_rows:
        reduced = list(row)
        for colour in range(COLOURS):
            mean = sum(row[node_index[(v, colour)]] for v in range(ORDER))
            for v in range(ORDER):
                reduced[node_index[(v, colour)]] -= Fraction(mean, ORDER)
        ghz_rows.append(reduced)
    rank_ghz = rational_rank(ghz_rows)
    print(f"  rank of GHZ-restricted incidence on S  : {rank_ghz}"
          "   (their 'incidence rank 18')")
    print(f"  rank L_GHZ (their invariants)          : {len(cells) - rank_ghz}")

    # the three extra L_GHZ directions are the pure matching indicators:
    # each has endpoint character u_c = sum_v e_{v,c}, zero in the GHZ quotient
    cell_index_local = {cell: position for position, cell in enumerate(cells)}
    pure_indicators = []
    for colour in range(COLOURS):
        word = (colour,) * ORDER
        matching = next(m for m in matchings_lowest_first(tuple(range(ORDER)))
                        if all(TABLE[e][0] == colour and TABLE[e][1] == colour
                               for e in m))
        row = [Fraction(0)] * len(cells)
        for edge in matching:
            row[cell_index_local[cell_of_edge(edge)]] += 1
        pure_indicators.append(row)
        del word, matching
    kernel_basis = _kernel_basis(full_rows, len(cells))
    combined = rational_rank([list(r) for r in kernel_basis + pure_indicators])
    print(f"  rank( L_S + <1_{{M_0}}, 1_{{M_1}}, 1_{{M_2}}> )         : {combined}")
    assert combined == len(cells) - rank_ghz, "pure indicators do not span the gap"
    print("  => L_S <= L_GHZ with rank gap 3 spanned exactly by the three pure")
    print("     matching indicators (character u_c, killed by the GHZ torus).")
    print("     Our torus is STRICTLY larger, so our invariance demand is")
    print("     strictly stronger; z passes it anyway.")

    exponent = circulation()
    z = [0] * len(cells)
    cell_index = {cell: position for position, cell in enumerate(cells)}
    for edge, value in exponent.items():
        z[cell_index[cell_of_edge(edge)]] += value
    image = [0] * len(nodes)
    for position, value in enumerate(z):
        if not value:
            continue
        for node, count in incidence_row(cells[position]).items():
            image[node_index[node]] += value * count
    assert not any(image), "z is NOT in our L_S"
    print("  z = sum_i (1_{B_i} - 1_{E_i}) lies in ker(unsigned incidence),")
    print("     i.e. in OUR L (not merely in the weaker GHZ-invariant lattice).")
    print("  => THEIR H IS OUR EXPONENT-LOCAL-SYSTEM HOLONOMY on their support.")

    # Zaslavsky picture: the cell graph of the support
    adjacency: dict[Node, list[Node]] = {node: [] for node in nodes}
    for cell in cells:
        u, v, i, j = cell
        adjacency[(u, i)].append((v, j))
        adjacency[(v, j)].append((u, i))
    seen: dict[Node, int] = {}
    components = 0
    bipartite_components = 0
    for node in nodes:
        if node in seen or not adjacency[node]:
            continue
        components += 1
        stack = [(node, 0)]
        seen[node] = 0
        member = []
        bipartite = True
        while stack:
            current, parity = stack.pop()
            member.append(current)
            for neighbour in adjacency[current]:
                if neighbour not in seen:
                    seen[neighbour] = 1 - parity
                    stack.append((neighbour, 1 - parity))
                elif seen[neighbour] == parity:
                    bipartite = False
        bipartite_components += int(bipartite)
    used_nodes = sum(1 for node in nodes if adjacency[node])
    print(f"  cell graph of S: {used_nodes} used nodes, {len(cells)} edges, "
          f"{components} components, {bipartite_components} bipartite")
    print(f"  frame-lattice rank |E| - |V_used| + #bipartite = "
          f"{len(cells) - used_nodes + bipartite_components}"
          f"  (matches rank L_S = {len(cells) - rank_full})")

    # shape of z itself
    z_edges = [cells[p] for p, value in enumerate(z) if value]
    degree: dict[Node, int] = {}
    for cell in z_edges:
        u, v, i, j = cell
        degree[(u, i)] = degree.get((u, i), 0) + 1
        degree[(v, j)] = degree.get((v, j), 0) + 1
    print(f"  support(z): {len(z_edges)} cells on {len(degree)} nodes, "
          f"degree multiset {sorted(degree.values())}, coefficients "
          f"{sorted({value for value in z if value})}")

    # every node has degree 2, so support(z) is a disjoint union of cycles
    z_adjacency: dict[Node, list[Node]] = {node: [] for node in degree}
    for cell in z_edges:
        u, v, i, j = cell
        z_adjacency[(u, i)].append((v, j))
        z_adjacency[(v, j)].append((u, i))
    visited: set[Node] = set()
    lengths = []
    for node in z_adjacency:
        if node in visited:
            continue
        length = 0
        current, previous = node, None
        while current not in visited:
            visited.add(current)
            length += 1
            nxt = next(n for n in z_adjacency[current] if n != previous)
            previous, current = current, nxt
        lengths.append(length)
    print(f"  z decomposes into cycles of lengths {sorted(lengths)} in the")
    print("     cell graph -- all EVEN, so z is an even-cycle (frame) element,")
    print("     NOT an odd handcuff.  In our corpus the odd handcuffs are the")
    print("     carriers of every 1 = -1 certificate, so this is the exact")
    print("     structural reason O1 has nothing to work with here.")
    assert all(length % 2 == 0 for length in lengths), "odd cycle in support(z)"
    return cells, cell_index, z


