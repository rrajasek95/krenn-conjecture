def _kernel_basis(rows: list[list[Fraction]], width: int) -> list[list[Fraction]]:
    """Rational basis of {x : x^T M = 0} for M the stacked incidence rows."""
    columns = len(rows[0])
    work = [[rows[r][c] for r in range(width)] for c in range(columns)]
    pivots = []
    pivot = 0
    for column in range(width):
        target = next((r for r in range(pivot, len(work)) if work[r][column]), None)
        if target is None:
            continue
        work[pivot], work[target] = work[target], work[pivot]
        head = work[pivot][column]
        work[pivot] = [entry / head for entry in work[pivot]]
        for r in range(len(work)):
            if r != pivot and work[r][column]:
                factor = work[r][column]
                work[r] = [a - factor * b for a, b in zip(work[r], work[pivot])]
        pivots.append(column)
        pivot += 1
    free = [c for c in range(width) if c not in pivots]
    basis = []
    for column in free:
        vector = [Fraction(0)] * width
        vector[column] = Fraction(1)
        for index, pivot_column in enumerate(pivots):
            vector[pivot_column] = -work[index][column]
        basis.append(vector)
    return basis


def rational_rank(rows: list[list[Fraction]]) -> int:
    """Exact rank over Q by fraction-free-ish Gaussian elimination."""
    work = [row[:] for row in rows]
    pivot = 0
    columns = len(work[0]) if work else 0
    for column in range(columns):
        target = next((r for r in range(pivot, len(work)) if work[r][column]), None)
        if target is None:
            continue
        work[pivot], work[target] = work[target], work[pivot]
        head = work[pivot][column]
        work[pivot] = [entry / head for entry in work[pivot]]
        for r in range(len(work)):
            if r != pivot and work[r][column]:
                factor = work[r][column]
                work[r] = [a - factor * b for a, b in zip(work[r], work[pivot])]
        pivot += 1
    return pivot


def hnf_with_transform(rows: list[list[int]]):
    """Row Hermite form H = U * M with U unimodular; integers throughout."""
    matrix = [list(row) for row in rows]
    transform = [[1 if a == b else 0 for b in range(len(rows))]
                 for a in range(len(rows))]
    pivot = 0
    columns = len(matrix[0]) if matrix else 0
    for column in range(columns):
        while True:
            nonzero = [r for r in range(pivot, len(matrix)) if matrix[r][column]]
            if len(nonzero) <= 1:
                break
            nonzero.sort(key=lambda r: abs(matrix[r][column]))
            low, high = nonzero[0], nonzero[1]
            quotient = matrix[high][column] // matrix[low][column]
            matrix[high] = [a - quotient * b
                            for a, b in zip(matrix[high], matrix[low])]
            transform[high] = [a - quotient * b
                               for a, b in zip(transform[high], transform[low])]
        nonzero = [r for r in range(pivot, len(matrix)) if matrix[r][column]]
        if not nonzero:
            continue
        target = nonzero[0]
        matrix[pivot], matrix[target] = matrix[target], matrix[pivot]
        transform[pivot], transform[target] = transform[target], transform[pivot]
        if matrix[pivot][column] < 0:
            matrix[pivot] = [-entry for entry in matrix[pivot]]
            transform[pivot] = [-entry for entry in transform[pivot]]
        for r in range(pivot):
            if matrix[r][column]:
                quotient = matrix[r][column] // matrix[pivot][column]
                if quotient:
                    matrix[r] = [a - quotient * b
                                 for a, b in zip(matrix[r], matrix[pivot])]
                    transform[r] = [a - quotient * b
                                    for a, b in zip(transform[r], transform[pivot])]
        pivot += 1
    return matrix, transform


def odd_relation(rows: list[list[int]]):
    """Our O1 test: integers c_k with sum c_k d_k = 0 and sum c_k odd.

    Encode epsilon in an extra Z/2 coordinate: append 1 to every exponent row
    and adjoin the row (0, ..., 0, 2).  An odd relation exists iff the unit
    vector (0, ..., 0, 1) lies in the row lattice.
    """
    if not rows:
        return None
    width = len(rows[0])
    augmented = [list(row) + [1] for row in rows]
    augmented.append([0] * width + [2])
    matrix, transform = hnf_with_transform(augmented)
    for index, row in enumerate(matrix):
        if any(row[:width]) or row[width] != 1:
            continue
        coefficients = transform[index][:len(rows)]
        epsilon_coefficient = transform[index][len(rows)]
        assert sum(coefficients) + 2 * epsilon_coefficient == 1
        assert all(sum(coefficients[k] * rows[k][column]
                       for k in range(len(rows))) == 0
                   for column in range(width))
        return tuple(coefficients)
    return None


