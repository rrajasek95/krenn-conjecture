"""P5 decisive prototype: construct the TRUE mixed arc at the committed exact
generic-L rational point, order by order, by solving the selected M30
compatibility row for the newest bend, then testing whether the other 38
compatibility rows (26 further mixed germs + the pure rows) vanish for free.

This is the numeric point-analogue of the Nakayama principality statement
   M_i = a_i*M30 + tau*sum_j B_ij*M_j
and of the tau-saturated special-fibre criterion of
`notes/tau-saturated-special-fibre-nakayama-criterion.md`:
if the mixed ideal is generated by M30 then killing M30 order by order must
kill every other row automatically.

It also produces the TRUE bend sequence r_0, r_1, r_2, ... whose generating
function is the object the notes conjecture to be
   N(T)/((1+z0*T)(1+z30*T)(1+z52*T)).
Berlekamp-Massey on that exact rational sequence reports the true recurrence.

Read-only with respect to the repository.
"""

